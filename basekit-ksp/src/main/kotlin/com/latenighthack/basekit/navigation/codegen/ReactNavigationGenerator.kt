package com.latenighthack.basekit.navigation.codegen

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies

/**
 * Emits the app-specific Kotlin/JS route model, router and browser-history sync for the web: the
 * counterpart of [ComposeNavigationGenerator], with the same router body (see [appendKotlinRouter]).
 * The router keeps plain lists, bumps `revision` and tells its change listeners after each change, and
 * names entries with strings.
 *
 * Exported to JavaScript:
 * - `BasekitWebRouter`, a router's view for React: `subscribe`/`getSnapshot` for `useSyncExternalStore`,
 *   a `BasekitWebStack` snapshot of its path, sheet and cover, `open(url)`, `root(url)`, `back`,
 *   `dismiss`, `didShow`, `reconcilePath` and `register` for a screen's navigation handler.
 * - `BasekitWebEntry`, one entry: its id, owner, `screen` (the `BasekitRoute` case, `detail`),
 *   presentation, `url` and `host`, the router its navigator reports to.
 * - `BasekitBrowserHistory`, which mirrors the top router's path in `window.history`.
 * - `createBasekitNavigationRouter(policy)`, for an app that builds its router in JavaScript.
 *
 * The React stack host is generated by the viewmodel processor beside the destination models, since
 * the React interop lives in basekit-viewmodel.
 */
class ReactNavigationGenerator(
    private val codeGenerator: CodeGenerator,
    private val dependencies: Dependencies,
    private val navigationPackage: String,
    private val actionObservers: Boolean = true,
) {
    fun generate(destinations: List<DestinationInfo>, hostedComponents: List<DestinationInfo> = emptyList()) {
        val byName = destinations.associateBy { it.qualifiedName }
        // As in [ComposeNavigationGenerator]: each target with a call site gets a `show` method.
        val targets = (destinations + hostedComponents)
            .flatMap { source -> source.edges.mapNotNull { edge -> byName[edge.targetQualifiedName] } }
            .distinctBy { it.qualifiedName }
        if (targets.isEmpty()) return

        val content = render(destinations, targets)
        codeGenerator.createNewFile(dependencies, navigationPackage, "BasekitReactNavigation", "kt").use {
            it.write(content.encodeToByteArray())
        }
    }

    private fun render(destinations: List<DestinationInfo>, targets: List<DestinationInfo>): String = buildString {
        val routed = destinations.filter { it.routePath != null && it.argsQualifiedName != null }
        appendLine("@file:Suppress(\"NON_EXPORTABLE_TYPE\")")
        appendLine("@file:OptIn(ExperimentalJsExport::class)")
        appendLine()
        appendLine("package $navigationPackage")
        appendLine()
        appendLine("import com.latenighthack.basekit.navigation.NavigationObserver")
        appendLine("import com.latenighthack.basekit.navigation.NavigationPresentation")
        appendLine("import com.latenighthack.basekit.navigation.NavigationPresentationObserver")
        appendLine("import com.latenighthack.basekit.navigation.NavigationResponder")
        appendLine("import com.latenighthack.basekit.navigation.NavigatorArgs")
        appendLine("import com.latenighthack.basekit.navigation.RouteMatch")
        appendLine("import com.latenighthack.basekit.navigation.RouteTable")
        appendLine("import com.latenighthack.basekit.navigation.runOnMainThread")
        if (actionObservers) appendLine("import com.latenighthack.basekit.viewmodel.ViewModelActionObserver")
        if (actionObservers) appendLine("import com.latenighthack.basekit.viewmodel.ViewModelObserver")
        appendLine("import kotlin.js.ExperimentalJsExport")
        appendLine("import kotlin.js.JsExport")
        appendLine()
        appendLine("// Generated by Basekit from the Kotlin navigation graph.")
        appendLine()
        appendLine("private var basekitEntryCount = 0")
        appendLine("/** A new entry, owner or handler id, unique in this page. */")
        appendLine("internal fun basekitNextId(): String = \"basekit-${'$'}{++basekitEntryCount}\"")
        appendLine()

        appendKotlinRouter(WebRouterFlavor, destinations, targets, actionObservers)
        appendLine()

        appendLine("/** The `BasekitRoute` case [route] is, as `BasekitWebEntry.screen` and the destination `kind` name it. */")
        appendLine("internal fun basekitScreen(route: BasekitRoute): String = when (route) {")
        destinations.forEach { appendLine("    is BasekitRoute.${it.routeClass} -> \"${it.screenKey}\"") }
        appendLine("}")
        appendLine()
        appendLine("/** The address of [route] from its destination's `@Route`, or null for a destination without one. */")
        appendLine("internal fun basekitUrl(route: BasekitRoute): String? = when (route) {")
        routed.forEach { appendLine("    is BasekitRoute.${it.routeClass} -> ${urlExpression(it.routePath!!)}") }
        if (routed.size < destinations.size) appendLine("    else -> null")
        appendLine("}")
        appendLine()
        appendLine("private fun basekitEncode(value: String): String = js(\"encodeURIComponent\")(value).unsafeCast<String>()")
        appendLine()
        if (routed.isNotEmpty()) {
            appendLine("private val basekitRoutes: RouteTable by lazy { RouteTable().also { GeneratedRoutes.register(it) } }")
        }
        if (routed.isNotEmpty()) {
            appendLine("/** [url] with each path segment decoded, as a browser address escapes them; `Route` decodes the query")
            appendLine(" * itself. A segment that decodes to one with a `/` no longer matches its template. */")
            appendLine("private fun basekitDecodePath(url: String): String {")
            appendLine("    val end = url.indexOfAny(charArrayOf('?', '#')).let { if (it < 0) url.length else it }")
            appendLine("    val path = url.substring(0, end).split('/').joinToString(\"/\") { segment ->")
            appendLine("        try { js(\"decodeURIComponent\")(segment).unsafeCast<String>() } catch (_: Throwable) { segment }")
            appendLine("    }")
            appendLine("    return path + url.substring(end)")
            appendLine("}")
        }
        appendLine("/** The route [url] opens, through `GeneratedRoutes`, or null when no `@Route` matches it. */")
        appendLine("internal fun basekitRoute(url: String): BasekitRoute? {")
        if (routed.isNotEmpty()) {
            appendLine("    val match = basekitRoutes.match(basekitDecodePath(url)) ?: return null")
            appendLine("    return BasekitRoute.of(match.args)")
        } else {
            appendLine("    return null")
        }
        appendLine("}")
        appendLine()

        appendLine("/**")
        appendLine(" * A policy that asks [decide] for each request's presentation: `'push'` (or nothing), `'sheet'`,")
        appendLine(" * `'fullScreenCover'` or `{ custom: id }` for the router's platform presenter.")
        appendLine(" */")
        appendLine("public fun basekitWebPolicy(decide: (BasekitWebRequest) -> dynamic): BasekitNavigationPolicy = BasekitNavigationPolicy { request ->")
        appendLine("    basekitWebDecision(decide(BasekitWebRequest(request)))")
        appendLine("}")
        appendLine()
        appendLine("internal fun basekitWebDecision(value: dynamic): BasekitNavigationDecision {")
        appendLine("    val presentation: BasekitPresentation = when {")
        appendLine("        value == null || value == undefined || value == \"push\" -> BasekitPresentation.Push")
        appendLine("        value == \"sheet\" -> BasekitPresentation.Sheet")
        appendLine("        value == \"fullScreenCover\" -> BasekitPresentation.FullScreenCover")
        appendLine("        jsTypeOf(value) == \"object\" && jsTypeOf(value.custom) == \"string\" -> BasekitPresentation.PlatformCustom(value.custom.unsafeCast<String>())")
        appendLine("        else -> error(\"Unknown Basekit presentation ${'$'}value: use 'push', 'sheet', 'fullScreenCover' or { custom: id }\")")
        appendLine("    }")
        appendLine("    return BasekitNavigationDecision(presentation)")
        appendLine("}")
        appendLine()

        appendLine("/** A router for an app that builds it in JavaScript; [policy] is as [basekitWebPolicy]'s `decide`. */")
        appendLine("@JsExport")
        appendLine("public fun createBasekitNavigationRouter(policy: ((BasekitWebRequest) -> dynamic)? = null): BasekitWebRouter =")
        appendLine("    BasekitNavigationRouter(policy?.let { basekitWebPolicy(it) } ?: BasekitDefaultNavigationPolicy).web")
        appendLine()

        appendLine("/** One router's path, sheet and cover, as `BasekitWebRouter.getSnapshot` gives them: the same object until the router changes. */")
        appendLine("@JsExport")
        appendLine("public class BasekitWebStack internal constructor(")
        appendLine("    public val path: Array<BasekitWebEntry>,")
        appendLine("    public val sheet: BasekitWebEntry?,")
        appendLine("    public val fullScreenCover: BasekitWebEntry?,")
        appendLine("    public val revision: Int,")
        appendLine(")")
        appendLine()

        appendLine("/** An entry of a router, the same object for as long as the entry stays in it. */")
        appendLine("@JsExport")
        appendLine("public class BasekitWebEntry internal constructor(")
        appendLine("    @JsExport.Ignore public val entry: BasekitNavigationEntry,")
        appendLine("    private val router: BasekitNavigationRouter,")
        appendLine(") {")
        appendLine("    public val id: String get() = entry.id")
        appendLine("    public val ownerId: String get() = entry.ownerId")
        appendLine("    /** The destination: its `BasekitRoute` case, such as `detail`. */")
        appendLine("    public val screen: String get() = basekitScreen(entry.route)")
        appendLine("    /** `push`, `sheet`, `fullScreenCover` or `custom`. */")
        appendLine("    public val presentation: String get() = when (entry.decision.presentation) {")
        appendLine("        BasekitPresentation.Push -> \"push\"")
        appendLine("        BasekitPresentation.Sheet -> \"sheet\"")
        appendLine("        BasekitPresentation.FullScreenCover -> \"fullScreenCover\"")
        appendLine("        is BasekitPresentation.PlatformCustom -> \"custom\"")
        appendLine("    }")
        appendLine("    /** The id of a custom presentation, or null. */")
        appendLine("    public val customPresentation: String? get() = (entry.decision.presentation as? BasekitPresentation.PlatformCustom)?.id")
        appendLine("    /** The entry's address from its destination's `@Route`, or null. */")
        appendLine("    public val url: String? get() = basekitUrl(entry.route)")
        appendLine("    /** The router this entry's navigator reports to: for a sheet, cover or custom entry, the router")
        appendLine("     * made for it, which presents what it opens over it; otherwise the router holding it. */")
        appendLine("    public val host: BasekitWebRouter get() = router.host(entry).web")
        appendLine("    /** The destination model built for this entry, kept while the entry is. */")
        appendLine("    @JsExport.Ignore public var model: Any? = null")
        appendLine("}")
        appendLine()

        appendLine("/** A navigation request, as a policy or a screen's navigation handler gets it. */")
        appendLine("@JsExport")
        appendLine("public class BasekitWebRequest internal constructor(@JsExport.Ignore public val request: BasekitNavigationRequest) {")
        appendLine("    public val ownerId: String get() = request.ownerId")
        appendLine("    public val screen: String get() = basekitScreen(request.route)")
        appendLine("    /** The call site, an `NavigationEdge` name such as `HOME_ON_OPEN_DETAIL`. */")
        appendLine("    public val edge: String get() = request.edge.name")
        appendLine("    public val url: String? get() = basekitUrl(request.route)")
        appendLine("    public val context: Any? get() = request.context")
        appendLine("}")
        appendLine()

        appendLine("/** A request a navigation handler claimed: present it, or finish it without presenting. */")
        appendLine("@JsExport")
        appendLine("public class BasekitWebTransaction internal constructor(private val transaction: BasekitNavigationTransaction) {")
        appendLine("    public fun presentDefault() { transaction.presentDefault() }")
        appendLine("    /** Presents as [presentation]: `'push'`, `'sheet'`, `'fullScreenCover'` or `{ custom: id }`. */")
        appendLine("    public fun present(presentation: dynamic) { transaction.present(basekitWebDecision(presentation)) }")
        appendLine("    public fun finish(result: Any?) { transaction.finish(result) }")
        appendLine("    public fun dismiss() { transaction.dismiss() }")
        appendLine("}")
        appendLine()

        appendLine("/**")
        appendLine(" * A [BasekitNavigationRouter] for JavaScript. [subscribe] and [getSnapshot] are functions, not")
        appendLine(" * methods, so React's `useSyncExternalStore(router.subscribe, router.getSnapshot)` can take them as")
        appendLine(" * they are. Each router has one: `router.web`.")
        appendLine(" */")
        appendLine("@JsExport")
        appendLine("public class BasekitWebRouter internal constructor(@JsExport.Ignore public val router: BasekitNavigationRouter) {")
        appendLine("    private var snapshot: BasekitWebStack? = null")
        appendLine("    private val entries = mutableMapOf<String, BasekitWebEntry>()")
        appendLine("    private var shownIds: Set<String> = emptySet()")
        appendLine()
        appendLine("    /** Calls [listener] after each change to this router's path, sheet, cover or custom entries; returns")
        appendLine("     * the function that stops it. */")
        appendLine("    public val subscribe: (listener: () -> Unit) -> (() -> Unit) = { listener -> router.addChangeListener(listener) }")
        appendLine("    /** This router's path, sheet and cover: the same object until the router changes. */")
        appendLine("    public val getSnapshot: () -> BasekitWebStack = {")
        appendLine("        snapshot?.takeIf { it.revision == router.revision } ?: build().also { snapshot = it }")
        appendLine("    }")
        appendLine()
        appendLine("    private fun build(): BasekitWebStack {")
        appendLine("        val stack = BasekitWebStack(")
        appendLine("            router.path.map { entry(it) }.toTypedArray(),")
        appendLine("            router.sheet?.let { entry(it) },")
        appendLine("            router.fullScreenCover?.let { entry(it) },")
        appendLine("            router.revision,")
        appendLine("        )")
        appendLine("        // An entry that left drops its wrapper and the model built for it; a root never was shown here.")
        appendLine("        val ids = (stack.path.map { it.id } + listOfNotNull(stack.sheet?.id, stack.fullScreenCover?.id)).toSet()")
        appendLine("        (shownIds - ids).forEach { entries.remove(it) }")
        appendLine("        shownIds = ids")
        appendLine("        return stack")
        appendLine("    }")
        appendLine()
        appendLine("    /** The wrapper of [entry], the same one while the entry stays in this router. */")
        appendLine("    @JsExport.Ignore")
        appendLine("    public fun entry(entry: BasekitNavigationEntry): BasekitWebEntry = entries.getOrPut(entry.id) { BasekitWebEntry(entry, router) }")
        appendLine()
        appendLine("    /** A root entry for the destination [url] opens, or null when no `@Route` matches it. */")
        appendLine("    public fun root(url: String): BasekitWebEntry? = basekitRoute(url)?.let { entry(router.root(it)) }")
        appendLine("    /** Opens the destination [url] matches, as a deep link; false when no `@Route` matches it. */")
        appendLine("    public fun open(url: String): Boolean { router.open(basekitRoute(url) ?: return false); return true }")
        appendLine("    /** Pops the top entry of the path, as system back does; false when the path is empty. */")
        appendLine("    public fun back(): Boolean {")
        appendLine("        val path = router.path")
        appendLine("        if (path.isEmpty()) return false")
        appendLine("        router.reconcilePath(path.dropLast(1)); return true")
        appendLine("    }")
        appendLine("    /** Keeps only the path entries with [ids], as the host shows them; the rest close. */")
        appendLine("    public fun reconcilePath(ids: Array<String>) { val kept = ids.toSet(); router.reconcilePath(router.path.filter { it.id in kept }) }")
        appendLine("    /** Dismisses [entry], as a closed sheet or a dismissed custom presentation does; its responder answers null. */")
        appendLine("    public fun dismiss(entry: BasekitWebEntry) {")
        appendLine("        when (entry.id) {")
        appendLine("            router.sheet?.id -> router.updateSheet(null)")
        appendLine("            router.fullScreenCover?.id -> router.updateFullScreenCover(null)")
        appendLine("            else -> router.dismiss(entry.id)")
        appendLine("        }")
        appendLine("    }")
        appendLine("    /** Reports [entry] shown when no navigator opened it, such as the root; see `BasekitNavigationRouter.didShow`. */")
        appendLine("    public fun didShow(entry: BasekitWebEntry) { router.didShow(entry.entry) }")
        appendLine("    /** Lets [handler] claim the requests [ownerId]'s navigator makes; returns the function that stops it. */")
        appendLine("    public fun register(ownerId: String, handler: (BasekitWebRequest, BasekitWebTransaction) -> Boolean): () -> Unit {")
        appendLine("        val token = router.register(ownerId) { request, transaction -> handler(BasekitWebRequest(request), BasekitWebTransaction(transaction)) }")
        appendLine("        return { router.unregister(ownerId, token) }")
        appendLine("    }")
        appendLine("    /** Shows the entries a policy presents as `{ custom: id }`. */")
        appendLine("    public fun setPlatformPresenter(presenter: ((BasekitWebEntry, String) -> Unit)?) {")
        appendLine("        router.platformPresenter = presenter?.let { present -> { presented, id -> present(entry(presented), id) } }")
        appendLine("    }")
        appendLine("    /** Removes a custom presentation when its entry leaves, by entry id. */")
        appendLine("    public fun setPlatformDismisser(dismisser: ((String) -> Unit)?) { router.platformDismisser = dismisser }")
        appendLine("}")
        appendLine()

        appendLine("/**")
        appendLine(" * Mirrors [router]'s path in `window.history`: each pushed entry adds a history entry at its `@Route`")
        appendLine(" * address (the current one when it has none), and browser back closes the entries over the one it")
        appendLine(" * returns to, answering their responders with null. Entries the router closes itself are popped from")
        appendLine(" * history. Sheets, covers and custom presentations add no history entry.")
        appendLine(" *")
        appendLine(" * [attach] opens the page's address as a deep link unless it is [root]'s, and starts mirroring.")
        appendLine(" * Browser forward is undone: the entries it would return to have closed. Leave guards, scroll")
        appendLine(" * restoration and modified clicks are the host's.")
        appendLine(" */")
        appendLine("@JsExport")
        appendLine("public class BasekitBrowserHistory(private val router: BasekitWebRouter, private val root: BasekitWebEntry? = null) {")
        appendLine("    private val window: dynamic = js(\"window\")")
        appendLine("    /** The path entries history holds, bottom first; history entry `i + 1` holds `mirrored[i]`. */")
        appendLine("    private var mirrored: List<String> = emptyList()")
        appendLine("    /** Set while a `history.go` this made runs: its `popstate` is not the user's. */")
        appendLine("    private var traversing = false")
        appendLine("    private var unsubscribe: (() -> Unit)? = null")
        appendLine("    private val onPopState: (dynamic) -> Unit = { event -> popped(event.state) }")
        appendLine()
        appendLine("    /** Opens the page's address and starts mirroring; returns the function that stops. */")
        appendLine("    public fun attach(): () -> Unit {")
        appendLine("        val address = currentAddress()")
        appendLine("        val opened = root?.url != address && router.open(address)")
        appendLine("        // The page's own history entry shows the root; a deep-linked entry is pushed over it.")
        appendLine("        window.history.replaceState(state(0), \"\", if (opened) root?.url ?: address else address)")
        appendLine("        mirrored = emptyList()")
        appendLine("        window.addEventListener(\"popstate\", onPopState)")
        appendLine("        unsubscribe = router.subscribe { sync() }")
        appendLine("        sync()")
        appendLine("        return { detach() }")
        appendLine("    }")
        appendLine()
        appendLine("    public fun detach() {")
        appendLine("        window.removeEventListener(\"popstate\", onPopState)")
        appendLine("        unsubscribe?.invoke(); unsubscribe = null")
        appendLine("    }")
        appendLine()
        appendLine("    private fun popped(state: dynamic) {")
        appendLine("        val raw = state?.basekitDepth")
        appendLine("        val depth = if (jsTypeOf(raw) == \"number\") raw.unsafeCast<Int>() else 0")
        appendLine("        if (traversing) { traversing = false; sync(); return }")
        appendLine("        when {")
        appendLine("            depth < mirrored.size -> { mirrored = mirrored.take(depth); router.reconcilePath(mirrored.toTypedArray()) }")
        appendLine("            depth > mirrored.size -> { traversing = true; window.history.go(mirrored.size - depth) }")
        appendLine("        }")
        appendLine("    }")
        appendLine()
        appendLine("    /** Pops the history entries of path entries that left, then pushes those that arrived. */")
        appendLine("    private fun sync() {")
        appendLine("        if (traversing) return")
        appendLine("        val path = router.router.path")
        appendLine("        var kept = 0")
        appendLine("        while (kept < mirrored.size && kept < path.size && mirrored[kept] == path[kept].id) kept++")
        appendLine("        if (mirrored.size > kept) {")
        appendLine("            val popped = mirrored.size - kept")
        appendLine("            mirrored = mirrored.take(kept); traversing = true")
        appendLine("            window.history.go(-popped)")
        appendLine("            return")
        appendLine("        }")
        appendLine("        for (index in kept until path.size) {")
        appendLine("            window.history.pushState(state(index + 1), \"\", basekitUrl(path[index].route) ?: currentAddress())")
        appendLine("        }")
        appendLine("        mirrored = path.map { it.id }")
        appendLine("    }")
        appendLine()
        appendLine("    private fun currentAddress(): String = \"${'$'}{window.location.pathname}${'$'}{window.location.search}\"")
        appendLine("    private fun state(depth: Int): dynamic { val state: dynamic = js(\"({})\"); state.basekitDepth = depth; return state }")
        appendLine("}")
    }

    /** [template] as a Kotlin string expression filling each `{name}` with `route.args.name`, encoded. */
    private fun urlExpression(template: String): String {
        val escaped = template.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        val filled = Regex("\\{([^}]+)}").replace(escaped) { match ->
            "\${basekitEncode(route.args.${match.groupValues[1]})}"
        }
        return "\"$filled\""
    }

    private val DestinationInfo.screenKey: String get() = routeClass.replaceFirstChar { it.lowercase() }
}

/** The web router's state: plain lists, string ids, and a revision and change listeners for React. */
internal val WebRouterFlavor = KotlinRouterFlavor(
    idType = "String",
    newId = "basekitNextId()",
    newOwnerId = "basekitNextId()",
    pathList = "mutableListOf<BasekitNavigationEntry>()",
    slotInit = "= null",
    atomicResolve = false,
    onChange = "changed()",
    extraMembers = listOf(
        "",
        "    /** Bumped after each change to the path, sheet, cover or custom entries. */",
        "    public var revision: Int = 0",
        "        private set",
        "    private val changeListeners = mutableListOf<() -> Unit>()",
        "    /** Calls [listener] after each change to the path, sheet, cover or custom entries; returns the function that stops it. */",
        "    public fun addChangeListener(listener: () -> Unit): () -> Unit {",
        "        val registration: () -> Unit = { listener() }",
        "        changeListeners += registration",
        "        return { changeListeners.remove(registration); Unit }",
        "    }",
        "    private fun changed() { revision++; changeListeners.toList().forEach { it() } }",
        "    /** This router for JavaScript. */",
        "    public val web: BasekitWebRouter by lazy { BasekitWebRouter(this) }",
    ),
)
