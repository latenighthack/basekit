package com.latenighthack.basekit.navigation.codegen

/**
 * How a generated Kotlin router keeps its state, so the Compose (Android) and web (Kotlin/JS) routers
 * share one body. [idType] and [newId] name the entry id, [pathList] and [slotInit] hold the path and
 * the sheet and cover slots, and [atomicResolve] says whether a responder resolves through an
 * `AtomicBoolean`. [onChange], when set, runs at the start of `syncPresentation`, which every change
 * to the path, sheet, cover or custom entries ends with; [extraMembers] go at the end of the router.
 */
internal class KotlinRouterFlavor(
    val idType: String,
    val newId: String,
    val newOwnerId: String,
    val pathList: String,
    val slotInit: String,
    val atomicResolve: Boolean,
    val onChange: String? = null,
    val extraMembers: List<String> = emptyList(),
)

internal val ComposeRouterFlavor = KotlinRouterFlavor(
    idType = "UUID",
    newId = "UUID.randomUUID()",
    newOwnerId = "UUID.randomUUID().toString()",
    pathList = "mutableStateListOf<BasekitNavigationEntry>()",
    slotInit = "by mutableStateOf(null)",
    atomicResolve = true,
)

/**
 * Renders the route model, decision, entry, request, policy and transaction types and the
 * `BasekitNavigationRouter` that implements `NavigationHost`, as the Swift router behaves.
 */
internal fun StringBuilder.appendKotlinRouter(
    flavor: KotlinRouterFlavor,
    destinations: List<DestinationInfo>,
    targets: List<DestinationInfo>,
    actionObservers: Boolean,
) {
    appendLine("public sealed interface BasekitRoute {")
    appendLine("    public val edge: NavigationEdge?")
    appendLine()
    destinations.forEach { destination ->
        val params = buildList {
            destination.argsQualifiedName?.let { add("public val args: $it") }
            add("override val edge: NavigationEdge?")
            destination.responseQualifiedName?.let { add("public val responder: NavigationResponder<$it>?") }
        }.joinToString(", ")
        appendLine("    public class ${destination.routeClass}($params) : BasekitRoute")
    }
    appendLine()
    appendLine("    public companion object {")
    appendLine("        public fun of(args: NavigatorArgs): BasekitRoute? = when (args) {")
    destinations.forEach { destination ->
        val argsType = destination.argsQualifiedName ?: return@forEach
        val responder = if (destination.responseQualifiedName != null) ", responder = null" else ""
        appendLine("            is $argsType -> ${destination.routeClass}(args, edge = null$responder)")
    }
    appendLine("            else -> null")
    appendLine("        }")
    appendLine("    }")
    appendLine("}")
    appendLine()

    appendLine("public sealed interface BasekitPresentation {")
    appendLine("    public data object Push : BasekitPresentation")
    appendLine("    public data object Sheet : BasekitPresentation")
    appendLine("    public data object FullScreenCover : BasekitPresentation")
    appendLine("    public data class PlatformCustom(val id: String) : BasekitPresentation")
    appendLine("}")
    appendLine()
    appendLine("public sealed interface BasekitTransition {")
    appendLine("    public data object Automatic : BasekitTransition")
    appendLine("    public data class Zoom(val sourceId: Any) : BasekitTransition")
    appendLine("    public data class Custom(val id: String) : BasekitTransition")
    appendLine("}")
    appendLine()
    appendLine("public data class BasekitNavigationDecision(")
    appendLine("    val presentation: BasekitPresentation = BasekitPresentation.Push,")
    appendLine("    val transition: BasekitTransition = BasekitTransition.Automatic,")
    appendLine(")")
    appendLine()
    appendLine("public class BasekitNavigationEntry(")
    appendLine("    public val id: ${flavor.idType} = ${flavor.newId},")
    appendLine("    public val ownerId: String = ${flavor.newOwnerId},")
    appendLine("    public val route: BasekitRoute,")
    appendLine("    public val edge: NavigationEdge? = null,")
    appendLine("    public val context: Any? = null,")
    appendLine("    public val decision: BasekitNavigationDecision = BasekitNavigationDecision(),")
    appendLine(") {")
    appendLine("    public fun with(decision: BasekitNavigationDecision): BasekitNavigationEntry = BasekitNavigationEntry(id, ownerId, route, edge, context, decision)")
    appendLine("    override fun equals(other: Any?): Boolean = other is BasekitNavigationEntry && other.id == id")
    appendLine("    override fun hashCode(): Int = id.hashCode()")
    appendLine("}")
    appendLine()
    appendLine("public class BasekitNavigationRequest(")
    appendLine("    public val ownerId: String,")
    appendLine("    public val route: BasekitRoute,")
    appendLine("    public val edge: NavigationEdge,")
    appendLine("    public val context: Any?,")
    appendLine(")")
    appendLine()
    appendLine("public fun interface BasekitNavigationPolicy {")
    appendLine("    public fun decision(request: BasekitNavigationRequest): BasekitNavigationDecision")
    appendLine("}")
    appendLine("public object BasekitDefaultNavigationPolicy : BasekitNavigationPolicy {")
    appendLine("    override fun decision(request: BasekitNavigationRequest): BasekitNavigationDecision = BasekitNavigationDecision()")
    appendLine("}")
    appendLine()

    appendLine("private class BasekitResponderProxy<T : Any>(")
    appendLine("    private val upstream: NavigationResponder<T>,")
    appendLine("    private val completed: () -> Unit,")
    appendLine(") : NavigationResponder<T> {")
    if (flavor.atomicResolve) {
        appendLine("    private val resolved = AtomicBoolean(false)")
        appendLine("    override fun respond(response: T?) {")
        appendLine("        if (!resolved.compareAndSet(false, true)) return")
    } else {
        appendLine("    private var resolved = false")
        appendLine("    override fun respond(response: T?) {")
        appendLine("        if (resolved) return; resolved = true")
    }
    appendLine("        upstream.respond(response); runOnMainThread(completed)")
    appendLine("    }")
    appendLine("}")
    appendLine()
    appendLine("/** The responder `open` gives a responding destination reached by a deep link: nobody waits for its")
    appendLine(" * result, so the result is discarded and the destination closes as it would anywhere else. */")
    appendLine("private class BasekitDiscardingResponder<T : Any> : NavigationResponder<T> {")
    appendLine("    override fun respond(response: T?) {}")
    appendLine("}")
    appendLine()
    appendLine("public class BasekitNavigationTransaction internal constructor(")
    appendLine("    private val router: BasekitNavigationRouter,")
    appendLine("    internal val entry: BasekitNavigationEntry,")
    appendLine(") {")
    appendLine("    private var claimed = false")
    appendLine("    public fun presentDefault() { if (claimed) return; claimed = true; router.present(entry, null) }")
    appendLine("    public fun present(decision: BasekitNavigationDecision) { if (claimed) return; claimed = true; router.present(entry, decision) }")
    appendLine("    public fun finish(result: Any?) { if (claimed) return; claimed = true; router.resolve(entry.id, result, dismiss = true) }")
    appendLine("    public fun dismiss() { finish(null) }")
    appendLine("    internal val isClaimed: Boolean get() = claimed")
    appendLine("}")
    appendLine()
    appendLine("public typealias BasekitNavigationHandler = (BasekitNavigationRequest, BasekitNavigationTransaction) -> Boolean")
    appendLine("public typealias BasekitPlatformPresenter = (BasekitNavigationEntry, String) -> Unit")
    appendLine()

    appendLine("/**")
    appendLine(" * Call it on the main thread, as the generated navigators do.")
    appendLine(" *")
    appendLine(" * [navigationObserver] receives the screens this router shows or dismisses without a navigator: a")
    appendLine(" * root or other entry the host made, a deep link, system back or a dismissed sheet. `basekitViewModel`")
    appendLine(" * also wraps each navigator it builds with this router in an `Observing…Navigator` reporting to it")
    if (actionObservers) {
        appendLine(" * and each view model in `observing` reporting to [viewModelObserver] and [actionObserver]. The routers this one makes, and those")
    } else {
        appendLine(" * The routers this one makes, and those")
    }
    appendLine(" * made with the `parent` constructor, report to their parent's observers.")
    appendLine(" */")
    appendLine("public class BasekitNavigationRouter private constructor(")
    appendLine("    private val policy: BasekitNavigationPolicy,")
    appendLine("    public val navigationObserver: NavigationObserver,")
    if (actionObservers) appendLine("    public val actionObserver: ViewModelActionObserver,")
    appendLine("    private val parent: BasekitNavigationRouter?,")
    appendLine(") : NavigationHost {")
    val noOpAction = if (actionObservers) " ViewModelActionObserver.NoOp," else ""
    appendLine("    public constructor(policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy) : this(policy, NavigationObserver.NoOp,$noOpAction null)")
    appendLine()
    appendLine("    /** A router reporting to [navigationObserver]${if (actionObservers) " and [actionObserver]" else ""}; pass `NoOp` for one you don't observe. */")
    if (actionObservers) {
        appendLine("    public constructor(")
        appendLine("        policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy,")
        appendLine("        navigationObserver: NavigationObserver,")
        appendLine("        actionObserver: ViewModelActionObserver,")
        appendLine("    ) : this(policy, navigationObserver, actionObserver, null)")
    } else {
        // Policy is required here so a trailing lambda still means the policy.
        appendLine("    public constructor(policy: BasekitNavigationPolicy, navigationObserver: NavigationObserver) : this(policy, navigationObserver, null)")
    }
    appendLine()
    appendLine("    private val pathEntries = ${flavor.pathList}")
    appendLine("    public val path: List<BasekitNavigationEntry> get() = pathEntries")
    appendLine("    public var sheet: BasekitNavigationEntry? ${flavor.slotInit}")
    appendLine("        private set")
    appendLine("    public var fullScreenCover: BasekitNavigationEntry? ${flavor.slotInit}")
    appendLine("        private set")
    appendLine("    public var platformPresenter: BasekitPlatformPresenter? = null")
    appendLine("    public var platformDismisser: ((${flavor.idType}) -> Unit)? = null")
    appendLine("    /** Called when `close` names an owner this router does not present: the owner of its root.")
    appendLine("     * Forward it to whatever presented this router (see the `parent` constructor). */")
    appendLine("    public var onCloseRoot: ((String, Any?) -> Unit)? = null")
    appendLine("    private val handlers = mutableMapOf<String, Pair<${flavor.idType}, BasekitNavigationHandler>>()")
    appendLine("    private val responders = mutableMapOf<${flavor.idType}, NavigationResponder<*>>()")
    appendLine("    private val customEntries = mutableMapOf<${flavor.idType}, BasekitNavigationEntry>()")
    appendLine("    /** The router made for each entry this router presents other than by push. */")
    appendLine("    private val children = mutableMapOf<${flavor.idType}, BasekitNavigationRouter>()")
    appendLine("    /** Set once this router's entry has left its parent: it presents nothing more. */")
    appendLine("    private var closed = false")
    appendLine("    /** This router's platform presenter, or else its parent's, as it is when used. */")
    appendLine("    private val presenter: BasekitPlatformPresenter? get() = platformPresenter ?: parent?.presenter")
    appendLine("    private val dismisser: ((${flavor.idType}) -> Unit)? get() = platformDismisser ?: parent?.dismisser")
    appendLine("    /** The router at the top of this one's tree, which remembers the entries reported shown. */")
    appendLine("    private val topRouter: BasekitNavigationRouter get() = parent?.topRouter ?: this")
    appendLine("    /** The entries without an edge (roots, deep links) whose showing this tree has reported. */")
    appendLine("    private val reportedEntryIds = mutableSetOf<${flavor.idType}>()")
    appendLine("    /** Set when [navigationObserver] also receives what this router presents and dismisses. */")
    appendLine("    private val presentationObserver = navigationObserver as? NavigationPresentationObserver")
    appendLine("    /** What this router presented as last reported to [presentationObserver], bottom first. */")
    appendLine("    private val presentedEntries = LinkedHashMap<${flavor.idType}, Pair<BasekitNavigationEntry, NavigationPresentation>>()")
    appendLine("    private val presentedRoots = mutableSetOf<${flavor.idType}>()")
    if (actionObservers) {
        appendLine()
        appendLine("    /** Receives the events of each view model `basekitViewModel` builds with this router, with its")
        appendLine("     * bindings, children and rows (see `ViewModelObserver`), as well as [actionObserver]. Routers made")
        appendLine("     * from this one use it unless they set their own. */")
        appendLine("    public var viewModelObserver: ViewModelObserver? = null")
        appendLine("        get() = field ?: parent?.viewModelObserver")
    }
    appendLine()
    appendLine("    /** A router for content presented by [parent], such as a modal that has its own stack and sheets.")
    appendLine("     * Closing this router's root (an owner it does not present) closes that owner's entry in [parent],")
    appendLine("     * which also resolves its responder, as a dismiss in [parent] does. Without a platform presenter")
    appendLine("     * or dismisser of its own it uses [parent]'s, and it reports to [parent]'s observers. This decides")
    appendLine("     * nothing about how [parent] presents the entry. [parent] makes one for each entry it presents")
    appendLine("     * other than by push; see [host]. */")
    val parentAction = if (actionObservers) " parent.actionObserver," else ""
    appendLine("    public constructor(parent: BasekitNavigationRouter, policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy) : this(policy, parent.navigationObserver,$parentAction parent) {")
    appendLine("        onCloseRoot = { ownerId, context -> parent.close(ownerId, context) }")
    appendLine("    }")
    appendLine()
    appendLine("    /** The router [entry]'s navigator reports to: build the entry's view model with it as `host`.")
    appendLine("     * For an entry this router, or a router it made, presents as a sheet, cover or custom")
    appendLine("     * presentation, that is the router made for the entry, so what the entry opens is presented from")
    appendLine("     * it, over the entry. For a pushed entry it is the router whose path holds it; otherwise this")
    appendLine("     * router. */")
    appendLine("    public fun host(entry: BasekitNavigationEntry): BasekitNavigationRouter = routerHolding(entry) ?: this")
    appendLine()
    appendLine("    public fun root(route: BasekitRoute, ownerId: String = ${flavor.newOwnerId}): BasekitNavigationEntry = BasekitNavigationEntry(ownerId = ownerId, route = route)")
    appendLine("    /** Opens [route] from outside the graph, such as a deep link. A responding destination opened")
    appendLine("     * without a responder gets one that discards its result, since nobody is waiting for it; it runs,")
    appendLine("     * responds and closes as it does when a navigator opens it. It is reported to [navigationObserver]")
    appendLine("     * as a `NavigatedTo` before it is presented. */")
    appendLine("    public fun open(route: BasekitRoute, ownerId: String = \"deep-link\") {")
    appendLine("        val responder: NavigationResponder<*>? = if (lacksResponder(route)) BasekitDiscardingResponder<Any>() else null")
    appendLine("        if (!closed) reportShown(route)")
    appendLine("        val edge = route.edge")
    appendLine("        if (edge != null) {")
    appendLine("            receive(ownerId, route, edge, null, responder)")
    appendLine("        } else {")
    appendLine("            val entryId = ${flavor.newId}; topRouter.reportedEntryIds += entryId")
    appendLine("            replacePath(listOf(BasekitNavigationEntry(id = entryId, route = attach(responder, route, entryId))))")
    appendLine("        }")
    appendLine("    }")
    appendLine("    public fun open(args: NavigatorArgs, ownerId: String = \"deep-link\"): Boolean { val route = BasekitRoute.of(args) ?: return false; open(route, ownerId); return true }")
    appendLine("    public fun open(match: RouteMatch, ownerId: String = \"deep-link\"): Boolean = open(match.args, ownerId)")
    appendLine()
    appendLine("    /** Reports [entry] shown, once, when neither a navigator nor [open] opened it: a root, or an entry")
    appendLine("     * the host made itself. `BasekitDestinationView` and the stack host call it as an entry appears; a")
    appendLine("     * host that shows entries its own way calls it too. An entry a navigator opened has an edge and was")
    appendLine("     * reported by its `Observing…Navigator`, so it is not reported again. */")
    appendLine("    public fun didShow(entry: BasekitNavigationEntry) {")
    appendLine("        if (!closed && entry.id !in presentedEntries && presentedRoots.add(entry.id)) {")
    appendLine("            presentationObserver?.onPresentation(HostNavigationEvents.presented(screen(entry.route), entry.id.toString(), \"ROOT\", null))")
    appendLine("        }")
    appendLine("        if (closed || entry.edge != null || !topRouter.reportedEntryIds.add(entry.id)) return")
    appendLine("        reportShown(entry.route)")
    appendLine("    }")
    appendLine()
    appendLine("    /** Sets the sheet, as a dismiss does with null; the replaced entry is reported closed and its")
    appendLine("     * responder resolves with null. */")
    appendLine("    public fun updateSheet(entry: BasekitNavigationEntry?) { sheet?.takeIf { it.id != entry?.id }?.let { reportClosed(listOf(it)) }; replaceSheet(entry) }")
    appendLine("    public fun updateFullScreenCover(entry: BasekitNavigationEntry?) { fullScreenCover?.takeIf { it.id != entry?.id }?.let { reportClosed(listOf(it)) }; replaceFullScreenCover(entry) }")
    appendLine()
    appendLine("    public fun register(ownerId: String, handler: BasekitNavigationHandler): ${flavor.idType} {")
    appendLine("        val token = ${flavor.newId}; handlers[ownerId] = token to handler; return token")
    appendLine("    }")
    appendLine("    public fun unregister(ownerId: String, token: ${flavor.idType}) { if (handlers[ownerId]?.first == token) handlers.remove(ownerId) }")
    appendLine()
    appendLine("    override fun close(ownerId: String, context: Any?) {")
    appendLine("        if (sheet?.ownerId == ownerId) { replaceSheet(null); return }")
    appendLine("        if (fullScreenCover?.ownerId == ownerId) { replaceFullScreenCover(null); return }")
    appendLine("        customEntries.values.firstOrNull { it.ownerId == ownerId }?.let { resolve(it.id, null, dismiss = true); return }")
    appendLine("        val index = pathEntries.indexOfFirst { it.ownerId == ownerId }")
    appendLine("        if (index < 0) { onCloseRoot?.invoke(ownerId, context); return }")
    appendLine("        val removed = pathEntries.subList(index, pathEntries.size).toList(); removeFrom(index); removed.forEach { resolve(it.id, null, dismiss = false) }")
    appendLine("    }")
    appendLine("    /** Finishes or dismisses entry [entryId] for the host, such as a custom presentation it dismissed:")
    appendLine("     * the entries it removes are reported closed. */")
    appendLine("    public fun finish(entryId: ${flavor.idType}, result: Any?) { reportClosed(presentedRemovedBy(entryId)); resolve(entryId, result, dismiss = true) }")
    appendLine("    public fun dismiss(entryId: ${flavor.idType}) { reportClosed(presentedRemovedBy(entryId)); resolve(entryId, null, dismiss = true) }")

    targets.forEach { target ->
        val params = buildList {
            add("ownerId: String")
            target.argsQualifiedName?.let { add("args: $it") }
            add("edge: NavigationEdge")
            add("context: Any?")
            target.responseQualifiedName?.let { add("responder: NavigationResponder<$it>") }
        }.joinToString(", ")
        val routeArgs = buildList {
            if (target.argsQualifiedName != null) add("args")
            add("edge")
            if (target.responseQualifiedName != null) add("responder")
        }.joinToString(", ")
        val responder = if (target.responseQualifiedName != null) ", responder" else ""
        appendLine("    override fun show${target.navName.toUpperCamelCase()}($params) {")
        appendLine("        receive(ownerId, BasekitRoute.${target.routeClass}($routeArgs), edge, context$responder)")
        appendLine("    }")
    }

    appendLine()
    appendLine("    private fun receive(ownerId: String, route: BasekitRoute, edge: NavigationEdge, context: Any?, responder: NavigationResponder<*>? = null) {")
    appendLine("        // A dismissed entry's view model can still navigate; nothing shows this router any more.")
    appendLine("        @Suppress(\"UNCHECKED_CAST\")")
    appendLine("        if (closed) { (responder as NavigationResponder<Any>?)?.respond(null); return }")
    appendLine("        val entryId = ${flavor.newId}; val routed = attach(responder, route, entryId)")
    appendLine("        val entry = BasekitNavigationEntry(id = entryId, route = routed, edge = edge, context = context)")
    appendLine("        val request = BasekitNavigationRequest(ownerId, routed, edge, context)")
    appendLine("        val transaction = BasekitNavigationTransaction(this, entry)")
    appendLine("        if (handlers[ownerId]?.second?.invoke(request, transaction) == true) {")
    appendLine("            if (!transaction.isClaimed) return")
    appendLine("        } else if (!transaction.isClaimed) { present(entry, policy.decision(request)) }")
    appendLine("    }")
    appendLine("    /** [route] with [responder] behind a proxy that resolves once and closes entry [entryId] when the")
    appendLine("     * destination responds; [route] unchanged when there is no responder. */")
    appendLine("    private fun attach(responder: NavigationResponder<*>?, route: BasekitRoute, entryId: ${flavor.idType}): BasekitRoute {")
    appendLine("        if (responder == null) return route")
    appendLine("        @Suppress(\"UNCHECKED_CAST\")")
    appendLine("        val proxy = BasekitResponderProxy(responder as NavigationResponder<Any>) { completeFromDestination(entryId) }")
    appendLine("        responders[entryId] = proxy; return replacingResponder(route, proxy)")
    appendLine("    }")
    appendLine("    internal fun present(entry: BasekitNavigationEntry, override: BasekitNavigationDecision?) {")
    appendLine("        val decided = if (override != null) entry.with(override) else entry")
    appendLine("        when (val presentation = decided.decision.presentation) {")
    appendLine("            BasekitPresentation.Push -> { pathEntries.add(decided); syncPresentation() }")
    appendLine("            BasekitPresentation.Sheet -> replaceSheet(decided)")
    appendLine("            BasekitPresentation.FullScreenCover -> replaceFullScreenCover(decided)")
    appendLine("            is BasekitPresentation.PlatformCustom -> {")
    appendLine("                val presenter = presenter")
    appendLine("                if (presenter != null) { adopt(decided); customEntries[decided.id] = decided; syncPresentation(); presenter(decided, presentation.id) } else { error(\"No Basekit platformPresenter for custom presentation ${'$'}{presentation.id}\") }")
    appendLine("            }")
    appendLine("        }")
    appendLine("    }")
    appendLine("    internal fun resolve(entryId: ${flavor.idType}, result: Any?, dismiss: Boolean) {")
    appendLine("        @Suppress(\"UNCHECKED_CAST\")")
    appendLine("        (responders.remove(entryId) as NavigationResponder<Any>?)?.respond(result)")
    appendLine("        if (!dismiss) return")
    appendLine("        if (sheet?.id == entryId) sheet = null; if (fullScreenCover?.id == entryId) fullScreenCover = null")
    appendLine("        val index = pathEntries.indexOfFirst { it.id == entryId }; if (index >= 0) removeFrom(index)")
    appendLine("        if (customEntries.remove(entryId) != null) dismisser?.invoke(entryId)")
    appendLine("        dropChild(entryId); syncPresentation()")
    appendLine("    }")
    appendLine("    private fun completeFromDestination(entryId: ${flavor.idType}) {")
    appendLine("        responders.remove(entryId); if (sheet?.id == entryId) sheet = null; if (fullScreenCover?.id == entryId) fullScreenCover = null")
    appendLine("        val index = pathEntries.indexOfFirst { it.id == entryId }; if (index >= 0) removeFrom(index)")
    appendLine("        if (customEntries.remove(entryId) != null) dismisser?.invoke(entryId)")
    appendLine("        dropChild(entryId); syncPresentation()")
    appendLine("    }")
    appendLine("    /** Makes the router [entry]'s navigator reports to, unless it has one: it presents with this")
    appendLine("     * router's policy and platform presenter. */")
    appendLine("    private fun adopt(entry: BasekitNavigationEntry) {")
    appendLine("        if (entry.id !in children) children[entry.id] = BasekitNavigationRouter(this, policy)")
    appendLine("    }")
    appendLine("    /** Removes the router made for [entryId], which left this router, with everything it presents. */")
    appendLine("    private fun dropChild(entryId: ${flavor.idType}) { children.remove(entryId)?.tearDown() }")
    appendLine("    /** Empties this router, whose entry left its parent: everything it presents goes, top first, and")
    appendLine("     * each responder still waiting answers null. */")
    appendLine("    private fun tearDown() {")
    appendLine("        closed = true")
    appendLine("        val nested = children.values.toList(); children.clear(); nested.forEach { it.tearDown() }")
    appendLine("        responders.keys.toList().forEach { respondNull(it) }")
    appendLine("        sheet = null; fullScreenCover = null; pathEntries.clear()")
    appendLine("        val custom = customEntries.keys.toList(); customEntries.clear(); custom.forEach { dismisser?.invoke(it) }")
    appendLine("        syncPresentation()")
    appendLine("    }")
    appendLine("    private fun routerHolding(entry: BasekitNavigationEntry): BasekitNavigationRouter? {")
    appendLine("        children[entry.id]?.let { return it }")
    appendLine("        if (pathEntries.any { it.id == entry.id }) return this")
    appendLine("        children.values.forEach { child -> child.routerHolding(entry)?.let { return it } }")
    appendLine("        return null")
    appendLine("    }")
    appendLine("    /** Sets the path as the host shows it, such as after system back. Each entry it removes is reported")
    appendLine("     * closed, top first, and its responder answers null. */")
    appendLine("    public fun reconcilePath(newPath: List<BasekitNavigationEntry>) {")
    appendLine("        val retained = newPath.map { it.id }.toSet(); val removed = pathEntries.filter { it.id !in retained }")
    appendLine("        reportClosed(removed.asReversed()); removed.forEach { resolve(it.id, null, dismiss = false) }; replacePath(newPath)")
    appendLine("    }")
    appendLine("    /** The entries that leave when entry [entryId] is dismissed, top first: it and, on the path, those over it. */")
    appendLine("    private fun presentedRemovedBy(entryId: ${flavor.idType}): List<BasekitNavigationEntry> {")
    appendLine("        sheet?.takeIf { it.id == entryId }?.let { return listOf(it) }")
    appendLine("        fullScreenCover?.takeIf { it.id == entryId }?.let { return listOf(it) }")
    appendLine("        customEntries[entryId]?.let { return listOf(it) }")
    appendLine("        val index = pathEntries.indexOfFirst { it.id == entryId }")
    appendLine("        return if (index < 0) emptyList() else pathEntries.subList(index, pathEntries.size).toList().asReversed()")
    appendLine("    }")
    appendLine("    private fun reportShown(route: BasekitRoute) {")
    appendLine("        navigationObserver.onNavigation(HostNavigationEvents.navigatedTo(screen(route), args(route)))")
    appendLine("    }")
    appendLine("    private fun reportClosed(entries: List<BasekitNavigationEntry>) {")
    appendLine("        entries.forEach { navigationObserver.onNavigation(HostNavigationEvents.closed(screen(it.route))) }")
    appendLine("    }")
    appendLine("    private fun screen(route: BasekitRoute): NavigationScreen = when (route) {")
    destinations.forEach { destination ->
        appendLine("        is BasekitRoute.${destination.routeClass} -> NavigationScreen.${destination.screenName}")
    }
    appendLine("    }")
    appendLine("    private fun args(route: BasekitRoute): NavigatorArgs? = when (route) {")
    destinations.forEach { destination ->
        val value = if (destination.argsQualifiedName != null) "route.args" else "null"
        appendLine("        is BasekitRoute.${destination.routeClass} -> $value")
    }
    appendLine("    }")
    appendLine("    private fun replacePath(newPath: List<BasekitNavigationEntry>) { pathEntries.clear(); pathEntries.addAll(newPath); syncPresentation() }")
    appendLine("    private fun removeFrom(index: Int) { pathEntries.subList(index, pathEntries.size).clear(); syncPresentation() }")
    appendLine("    /** Reports to [presentationObserver] the entries that left since the last call, top first, then")
    appendLine("     * those that arrived, bottom first. Nothing is tracked without one. */")
    appendLine("    private fun syncPresentation() {")
    flavor.onChange?.let { appendLine("        $it") }
    appendLine("        val observer = presentationObserver ?: return")
    appendLine("        val current = LinkedHashMap<${flavor.idType}, Pair<BasekitNavigationEntry, NavigationPresentation>>()")
    appendLine("        pathEntries.forEach { current[it.id] = it to NavigationPresentation.PUSH }")
    appendLine("        customEntries.values.forEach { current[it.id] = it to NavigationPresentation.CUSTOM }")
    appendLine("        sheet?.let { current[it.id] = it to NavigationPresentation.SHEET }")
    appendLine("        fullScreenCover?.let { current[it.id] = it to NavigationPresentation.FULL_SCREEN_COVER }")
    appendLine("        presentedEntries.keys.filter { it !in current }.asReversed().forEach { id ->")
    appendLine("            val (entry, presentation) = presentedEntries.remove(id) ?: return@forEach")
    appendLine("            observer.onPresentation(HostNavigationEvents.dismissed(screen(entry.route), id.toString(), presentation.name))")
    appendLine("        }")
    appendLine("        current.forEach { (id, presented) ->")
    appendLine("            if (id in presentedEntries) return@forEach")
    appendLine("            presentedEntries[id] = presented")
    appendLine("            val (entry, presentation) = presented")
    appendLine("            val customId = (entry.decision.presentation as? BasekitPresentation.PlatformCustom)?.id")
    appendLine("            observer.onPresentation(HostNavigationEvents.presented(screen(entry.route), id.toString(), presentation.name, customId))")
    appendLine("        }")
    appendLine("    }")
    appendLine("    private fun replaceSheet(replacement: BasekitNavigationEntry?) {")
    appendLine("        val removedId = if (sheet?.id != replacement?.id) sheet?.id else null; replacement?.let { adopt(it) }; sheet = replacement")
    appendLine("        syncPresentation(); removedId?.let { respondNull(it); dropChild(it) }")
    appendLine("    }")
    appendLine("    private fun replaceFullScreenCover(replacement: BasekitNavigationEntry?) {")
    appendLine("        val removedId = if (fullScreenCover?.id != replacement?.id) fullScreenCover?.id else null; replacement?.let { adopt(it) }; fullScreenCover = replacement")
    appendLine("        syncPresentation(); removedId?.let { respondNull(it); dropChild(it) }")
    appendLine("    }")
    appendLine("    private fun respondNull(entryId: ${flavor.idType}) {")
    appendLine("        @Suppress(\"UNCHECKED_CAST\")")
    appendLine("        (responders.remove(entryId) as NavigationResponder<Any>?)?.respond(null)")
    appendLine("    }")
    appendLine("    /** Whether [route] is for a responding destination but carries no responder. */")
    appendLine("    private fun lacksResponder(route: BasekitRoute): Boolean = when (route) {")
    destinations.filter { it.responseQualifiedName != null }.forEach { destination ->
        appendLine("        is BasekitRoute.${destination.routeClass} -> route.responder == null")
    }
    appendLine("        else -> false")
    appendLine("    }")
    appendLine("    @Suppress(\"UNCHECKED_CAST\")")
    appendLine("    private fun replacingResponder(route: BasekitRoute, responder: NavigationResponder<Any>): BasekitRoute = when (route) {")
    destinations.filter { it.responseQualifiedName != null }.forEach { destination ->
        val values = buildList {
            if (destination.argsQualifiedName != null) add("route.args")
            add("route.edge")
            add("responder as NavigationResponder<${destination.responseQualifiedName}>")
        }.joinToString(", ")
        appendLine("        is BasekitRoute.${destination.routeClass} -> BasekitRoute.${destination.routeClass}($values)")
    }
    appendLine("        else -> route")
    appendLine("    }")
    flavor.extraMembers.forEach { appendLine(it) }
    appendLine("}")
}

internal val DestinationInfo.routeClass: String get() = navName.toUpperCamelCase()
