        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("private struct BasekitNavigationHandlerModifier: ViewModifier {")
        appendLine("    @ObservedObject var router: BasekitNavigationRouter")
        appendLine("    let ownerID: String; let handler: BasekitNavigationHandler; @State private var token: UUID?")
        appendLine("    func body(content: Content) -> some View { content.onAppear { token = router.register(ownerID: ownerID, handler: handler) }.onDisappear { if let token { router.unregister(ownerID: ownerID, token: token) } } }")
        appendLine("}")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public extension View {")
        appendLine("    func basekitNavigationHandler(router: BasekitNavigationRouter, ownerID: String, _ handler: @escaping BasekitNavigationHandler) -> some View { modifier(BasekitNavigationHandlerModifier(router: router, ownerID: ownerID, handler: handler)) }")
        appendLine("}")
