            val swiftArgs = destination.argsSwiftName ?: return@forEach
            val routeName = destination.navName.toSwiftCase()
            val responseArg = if (destination.responseQualifiedName != null) ", responder: nil" else ""
            appendLine("        ${if (firstArgsBranch) "if" else "else if"} let typed = args as? $swiftArgs { self = .$routeName(args: typed, edge: nil$responseArg) }")
            firstArgsBranch = false
        }
        if (firstArgsBranch) appendLine("        return nil") else appendLine("        else { return nil }")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
