        appendLine("/// The router's stack with its sheet and full-screen cover. [root] and [destination] get each entry with")
        appendLine("/// the router its navigator reports to, the `host` to build its view model with. A sheet or cover shows")
        appendLine("/// a stack of its own for the router made for its entry (see `BasekitNavigationRouter.host(for:)`), with")
        appendLine("/// the entry at its root, so what it opens is presented over it, and the sheets it opens stack.")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public struct BasekitNavigationStackHost<Root: View, Destination: View>: View {")
        appendLine("    @ObservedObject private var router: BasekitNavigationRouter")
        appendLine("    private let rootEntry: BasekitNavigationEntry")
        appendLine("    private let root: (BasekitNavigationEntry, BasekitNavigationRouter, Namespace.ID) -> Root")
        appendLine("    private let destination: (BasekitNavigationEntry, BasekitNavigationRouter, Namespace.ID) -> Destination")
        appendLine("    @Namespace private var namespace")
        appendLine("    public init(router: BasekitNavigationRouter, rootEntry: BasekitNavigationEntry, @ViewBuilder root: @escaping (BasekitNavigationEntry, BasekitNavigationRouter, Namespace.ID) -> Root, @ViewBuilder destination: @escaping (BasekitNavigationEntry, BasekitNavigationRouter, Namespace.ID) -> Destination) { self.router = router; self.rootEntry = rootEntry; self.root = root; self.destination = destination }")
        appendLine("    public var body: some View {")
        appendLine("        NavigationStack(path: router.pathBinding) {")
        appendLine("            root(rootEntry, router, namespace).onAppear { router.didShow(rootEntry) }.navigationDestination(for: BasekitNavigationEntry.self) { entry in")
        appendLine("                transitioned(entry, destination(entry, router, namespace)).onAppear { router.didShow(entry) }")
        appendLine("            }")
        appendLine("        }.sheet(item: router.sheetBinding) { transitioned($0, presented($0)) }")
        appendLine("#if canImport(UIKit)")
        appendLine("        .fullScreenCover(item: router.fullScreenCoverBinding) { transitioned($0, presented($0)) }")
        appendLine("#else")
        appendLine("        .sheet(item: router.fullScreenCoverBinding) { transitioned($0, presented($0)) }")
        appendLine("#endif")
        appendLine("    }")
        appendLine("    /// [entry]'s own stack. `AnyView`, as the stack host's body would otherwise name its own type.")
        appendLine("    private func presented(_ entry: BasekitNavigationEntry) -> AnyView {")
        appendLine("        AnyView(BasekitPresentedStackHost(parent: router, entry: entry, destination: destination))")
        appendLine("    }")
        appendLine("    @ViewBuilder private func transitioned(_ entry: BasekitNavigationEntry, _ content: some View) -> some View {")
        appendLine("        switch entry.decision.transition {")
        appendLine("        case .zoom(let sourceID):")
        appendLine("#if canImport(UIKit)")
        appendLine("            content.navigationTransition(.zoom(sourceID: sourceID, in: namespace))")
        appendLine("#else")
        appendLine("            content.navigationTransition(.automatic)")
        appendLine("#endif")
        appendLine("        case .automatic, .custom: content.navigationTransition(.automatic)")
        appendLine("        }")
        appendLine("    }")
        appendLine("}")
        appendLine()
        appendLine("/// A presented entry's stack, for the router made for it. It keeps that router for the view's identity, so")
        appendLine("/// a redraw while the entry is dismissed shows the same router rather than the presenting one.")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
