        appendLine("    public var animatorProvider: (@MainActor (UINavigationController.Operation, UIViewController, UIViewController, BasekitNavigationEntry?) -> UIViewControllerAnimatedTransitioning?)?")
        appendLine("    public var interactionProvider: (@MainActor (UIViewControllerAnimatedTransitioning) -> UIViewControllerInteractiveTransitioning?)?")
        appendLine("    public let navigationController: UINavigationController")
        appendLine("    private let router: BasekitNavigationRouter; private let factory: Factory; private var root: BasekitNavigationEntry; private var cancellables: Set<AnyCancellable> = []")
        appendLine("    /// Each shown entry's controller, made once and kept while the entry is on the path, so a screen that stays keeps its state.")
        appendLine("    private var controllers: [UUID: UIViewController] = [:]")
        appendLine("    public init(router: BasekitNavigationRouter, root: BasekitNavigationEntry, navigationController: UINavigationController, factory: @escaping Factory) {")
        appendLine("        self.router = router; self.root = root; self.navigationController = navigationController; self.factory = factory; super.init(); navigationController.viewControllers = [controller(for: root)]; navigationController.delegate = self")
        appendLine("        router.\$path.sink { [weak self] path in self?.synchronize(path) }.store(in: &cancellables)")
        appendLine("    }")
        appendLine("    public convenience init(router: BasekitNavigationRouter, root: BasekitNavigationEntry, factory: @escaping Factory) { self.init(router: router, root: root, navigationController: UINavigationController(), factory: factory) }")
        appendLine("    private func controller(for entry: BasekitNavigationEntry) -> UIViewController {")
        appendLine("        if let existing = controllers[entry.id] { return existing }")
        appendLine("        let made = factory(entry); controllers[entry.id] = made; return made")
        appendLine("    }")
        appendLine("    /// The stack to finish with once UIKit shows the push or pop that leads to it.")
        appendLine("    private var stackAfterTransition: [UIViewController]?")
        appendLine("    /// Setting that stack, which UIKit may report as shown; the path is already right.")
        appendLine("    private var isSettingStack = false")
        appendLine("    /// Shows [path] over the root, whatever changed in it. A path that adds one entry pushes it; one that drops entries")
        appendLine("    /// from the top pops back. Any other change, such as a different top entry, pushes or pops to its top screen and")
        appendLine("    /// then sets the screens under it without animation: UIKit's animated stack change misplaces screens after a")
        appendLine("    /// transition that ended early. Entries that stay keep their controllers. During a transition it waits, then shows")
        appendLine("    /// the router's path as it is by then.")
        appendLine("    private func synchronize(_ path: [BasekitNavigationEntry]) {")
        appendLine("        if let transition = navigationController.transitionCoordinator {")
        appendLine("            transition.animate(alongsideTransition: nil) { [weak self] _ in guard let self else { return }; self.synchronize(self.router.path) }")
        appendLine("            return")
        appendLine("        }")
        appendLine("        guard stackAfterTransition == nil else { return }")
        appendLine("        let entries = [root] + path; let shownIDs = Set(entries.map(\\.id)); controllers = controllers.filter { shownIDs.contains(\$0.key) }")
        appendLine("        let wanted = entries.map(controller(for:)); let current = navigationController.viewControllers")
        appendLine("        guard !wanted.elementsEqual(current, by: ===), let top = wanted.last else { return }")
        appendLine("        // Off screen, or with the same top screen, there's nothing to animate.")
        appendLine("        if navigationController.viewIfLoaded?.window == nil || current.last === top { navigationController.setViewControllers(wanted, animated: false); return }")
        appendLine("        if wanted.count == current.count + 1, wanted.dropLast().elementsEqual(current, by: ===) { navigationController.pushViewController(top, animated: true); return }")
        appendLine("        if wanted.count < current.count, current.prefix(wanted.count).elementsEqual(wanted, by: ===) { navigationController.popToViewController(top, animated: true); return }")
        appendLine("        stackAfterTransition = wanted")
        appendLine("        if current.contains(where: { \$0 === top }) { navigationController.popToViewController(top, animated: true) } else { navigationController.pushViewController(top, animated: true) }")
        appendLine("    }")
        appendLine("    /// Finishes a change that ended on a push or pop, then shows the router's path as it is now. Otherwise someone else")
        appendLine("    /// moved the stack, such as Back or a swipe, and the path follows the screens that are left.")
        appendLine("    public func navigationController(_ navigationController: UINavigationController, didShow viewController: UIViewController, animated: Bool) {")
        appendLine("        if let stack = stackAfterTransition {")
        appendLine("            stackAfterTransition = nil")
        appendLine("            if viewController === stack.last { isSettingStack = true; navigationController.setViewControllers(stack, animated: false); isSettingStack = false }")
        appendLine("            DispatchQueue.main.async { [weak self] in guard let self else { return }; self.synchronize(self.router.path) }")
        appendLine("            return")
        appendLine("        }")
        appendLine("        guard !isSettingStack else { return }")
        appendLine("        let visiblePathCount = max(0, navigationController.viewControllers.count - 1); if visiblePathCount < router.path.count { router.reconcilePath(Array(router.path.prefix(visiblePathCount))) }")
        appendLine("    }")
        appendLine("    public func navigationController(_ navigationController: UINavigationController, animationControllerFor operation: UINavigationController.Operation, from fromVC: UIViewController, to toVC: UIViewController) -> UIViewControllerAnimatedTransitioning? { animatorProvider?(operation, fromVC, toVC, router.path.last) }")
        appendLine("    public func navigationController(_ navigationController: UINavigationController, interactionControllerFor animationController: UIViewControllerAnimatedTransitioning) -> UIViewControllerInteractiveTransitioning? { interactionProvider?(animationController) }")
        appendLine("}")
        appendLine("#elseif canImport(AppKit)")
        appendLine("@available(macOS 15.0, *)")
        appendLine("@MainActor public protocol BasekitAppKitPresenter: AnyObject {")
        appendLine("    func present(entry: BasekitNavigationEntry, customID: String)")
        appendLine("    func dismiss(entryID: UUID)")
        appendLine("}")
        appendLine("@available(macOS 15.0, *)")
        appendLine("@MainActor public extension BasekitNavigationRouter {")
        appendLine("    func use(appKitPresenter presenter: BasekitAppKitPresenter) {")
        appendLine("        platformPresenter = { [weak presenter] entry, customID in presenter?.present(entry: entry, customID: customID) }")
        appendLine("        platformDismisser = { [weak presenter] entryID in presenter?.dismiss(entryID: entryID) }")
        appendLine("    }")
        appendLine("}")
        appendLine("#endif")
    }

    private fun String.toSwiftCase(): String = toUpperCamelCase().replaceFirstChar { it.lowercase() }
    private fun String.toSwiftEnumCase(): String = lowercase().split('_').let { parts ->
        parts.first() + parts.drop(1).joinToString("") { it.replaceFirstChar(Char::uppercase) }
    }
