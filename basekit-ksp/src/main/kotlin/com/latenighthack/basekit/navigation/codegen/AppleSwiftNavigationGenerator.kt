        appendLine("        let host = parent.host(for: entry); _router = StateObject(wrappedValue: host); self.entry = entry; self.destination = destination")
        appendLine("    }")
        appendLine("    var body: some View {")
        appendLine("        BasekitNavigationStackHost(router: router, rootEntry: entry, root: destination, destination: destination)")
