package com.latenighthack.basekit.navigation.codegen

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies

/** Emits the app-specific Swift route model, router, interception API, and native renderers. */
class AppleSwiftNavigationGenerator(
    private val codeGenerator: CodeGenerator,
    private val dependencies: Dependencies,
    private val frameworkImports: List<String>,
) {
    private data class Site(
        val edge: NavEdge,
        val target: DestinationInfo,
        // kotlinName must match AppleHostedNavigatorGenerator's AppleNavigationEdge entry so the
        // BasekitNavigationEdge(_:) switch stays exhaustive. Both are target-disambiguated on fan-out.
        val kotlinName: String,
        val swiftName: String,
    )

    fun generate(destinations: List<DestinationInfo>, hostedComponents: List<DestinationInfo> = emptyList()) {
        val byName = destinations.associateBy { it.qualifiedName }
        // Hosted components contribute call sites; only destinations are routes.
        val rawSites = (destinations + hostedComponents).flatMap { source ->
            source.edges.mapNotNull { edge -> byName[edge.targetQualifiedName]?.let { edge to it } }
        }.distinctBy { (edge, _) -> edge }
        if (rawSites.isEmpty()) return

        // Kept in lockstep with AppleHostedNavigatorGenerator: a fan-out action (multiple @NavigateTo)
        // produces call sites sharing a source+method base name, so disambiguate by target.
        val colliding = rawSites.groupingBy { (edge, _) -> edge.sourceEntry }
            .eachCount().filterValues { it > 1 }.keys
        val sites = rawSites.map { (edge, target) ->
            val fanOut = edge.sourceEntry in colliding
            val kotlinName = if (fanOut) "${edge.sourceEntry}_TO_${target.navName.uppercase()}" else edge.sourceEntry
            val swiftRaw = if (fanOut) {
                "${edge.sourceNavName}_${edge.methodName}_to_${target.navName}"
            } else {
                "${edge.sourceNavName}_${edge.methodName}"
            }
            Site(edge, target, kotlinName, swiftRaw.toUpperCamelCase().replaceFirstChar { it.lowercase() })
        }
        if (sites.isEmpty()) return

        val content = render(destinations, sites)
        codeGenerator.createNewFile(dependencies, "", "BasekitAppleNavigation", "swift").use {
            it.write(content.encodeToByteArray())
        }
    }

    private fun render(destinations: List<DestinationInfo>, sites: List<Site>): String = buildString {
        frameworkImports.forEach { appendLine("import $it") }
        appendLine("import Foundation")
        appendLine("import Combine")
        appendLine("import SwiftUI")
        appendLine("#if canImport(UIKit)")
        appendLine("import UIKit")
        appendLine("#elseif canImport(AppKit)")
        appendLine("import AppKit")
        appendLine("#endif")
        appendLine()
        appendLine("// Generated by Basekit from the Kotlin navigation graph.")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public enum BasekitNavigationEdge: Hashable {")
        sites.forEach { appendLine("    case ${it.swiftName}") }
        appendLine()
        appendLine("    init(_ edge: AppleNavigationEdge) {")
        appendLine("        switch edge {")
        sites.forEach { appendLine("        case .${it.kotlinName.toSwiftEnumCase()}: self = .${it.swiftName}") }
        appendLine("        }")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public enum BasekitRoute {")
        destinations.forEach { destination ->
            val routeName = destination.navName.toSwiftCase()
            val params = buildList {
                destination.argsSwiftName?.let { add("args: $it") }
                add("edge: BasekitNavigationEdge?")
                if (destination.responseQualifiedName != null) add("responder: NavigationResponder?")
            }.joinToString(", ")
            appendLine("    case $routeName($params)")
        }
        appendLine("}")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public extension BasekitRoute {")
        appendLine("    init?(args: NavigatorArgs) {")
        var firstArgsBranch = true
        destinations.forEach { destination ->
            val swiftArgs = destination.argsSwiftName ?: return@forEach
            val routeName = destination.navName.toSwiftCase()
            val responseArg = if (destination.responseQualifiedName != null) ", responder: nil" else ""
            appendLine("        ${if (firstArgsBranch) "if" else "else if"} let typed = args as? $swiftArgs { self = .$routeName(args: typed, edge: nil$responseArg) }")
            firstArgsBranch = false
        }
        if (firstArgsBranch) appendLine("        return nil") else appendLine("        else { return nil }")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public enum BasekitPresentation: Equatable {")
        appendLine("    case push")
        appendLine("    case sheet")
        appendLine("    case fullScreenCover")
        appendLine("    case platformCustom(id: String)")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public enum BasekitTransition: Equatable {")
        appendLine("    case automatic")
        appendLine("    case zoom(sourceID: AnyHashable)")
        appendLine("    case custom(id: String)")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public struct BasekitNavigationDecision: Equatable {")
        appendLine("    public var presentation: BasekitPresentation")
        appendLine("    public var transition: BasekitTransition")
        appendLine("    public init(presentation: BasekitPresentation = .push, transition: BasekitTransition = .automatic) {")
        appendLine("        self.presentation = presentation")
        appendLine("        self.transition = transition")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public struct BasekitNavigationEntry: Identifiable, Hashable {")
        appendLine("    public let id: UUID")
        appendLine("    public let ownerID: String")
        appendLine("    public let route: BasekitRoute")
        appendLine("    public let edge: BasekitNavigationEdge?")
        appendLine("    public let context: Any?")
        appendLine("    public var decision: BasekitNavigationDecision")
        appendLine("    public init(id: UUID = UUID(), ownerID: String = UUID().uuidString, route: BasekitRoute, edge: BasekitNavigationEdge? = nil, context: Any? = nil, decision: BasekitNavigationDecision = .init()) {")
        appendLine("        self.id = id; self.ownerID = ownerID; self.route = route; self.edge = edge; self.context = context; self.decision = decision")
        appendLine("    }")
        appendLine("    public static func == (lhs: Self, rhs: Self) -> Bool { lhs.id == rhs.id }")
        appendLine("    public func hash(into hasher: inout Hasher) { hasher.combine(id) }")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public struct BasekitNavigationRequest {")
        appendLine("    public let ownerID: String")
        appendLine("    public let route: BasekitRoute")
        appendLine("    public let edge: BasekitNavigationEdge")
        appendLine("    public let context: Any?")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public protocol BasekitNavigationPolicy {")
        appendLine("    @MainActor func decision(for request: BasekitNavigationRequest) -> BasekitNavigationDecision")
        appendLine("}")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public struct BasekitDefaultNavigationPolicy: BasekitNavigationPolicy {")
        appendLine("    public init() {}")
        appendLine("    @MainActor public func decision(for request: BasekitNavigationRequest) -> BasekitNavigationDecision { .init() }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("private final class BasekitResponderProxy: NSObject, NavigationResponder {")
        appendLine("    private let upstream: NavigationResponder; private let completed: @MainActor () -> Void; private let lock = NSLock(); private var resolved = false")
        appendLine("    init(upstream: NavigationResponder, completed: @escaping @MainActor () -> Void) { self.upstream = upstream; self.completed = completed }")
        appendLine("    func respond(response: Any?) {")
        appendLine("        lock.lock(); guard !resolved else { lock.unlock(); return }; resolved = true; lock.unlock()")
        appendLine("        upstream.respond(response: response); let completion = completed; Task { @MainActor in completion() }")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("/// The responder `open` gives a responding destination reached by a deep link: nobody waits for its")
        appendLine("/// result, so the result is discarded and the destination closes as it would anywhere else.")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("private final class BasekitDiscardingResponder: NSObject, NavigationResponder {")
        appendLine("    func respond(response: Any?) {}")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("@MainActor public final class BasekitNavigationTransaction {")
        appendLine("    private weak var router: BasekitNavigationRouter?")
        appendLine("    fileprivate let entry: BasekitNavigationEntry")
        appendLine("    private var claimed = false")
        appendLine("    fileprivate init(router: BasekitNavigationRouter, entry: BasekitNavigationEntry) { self.router = router; self.entry = entry }")
        appendLine("    public func presentDefault() { guard !claimed else { return }; claimed = true; router?.present(entry, override: nil) }")
        appendLine("    public func present(using decision: BasekitNavigationDecision) { guard !claimed else { return }; claimed = true; router?.present(entry, override: decision) }")
        appendLine("    public func finish(with result: Any?) { guard !claimed else { return }; claimed = true; router?.resolve(entryID: entry.id, result: result, dismiss: true) }")
        appendLine("    public func dismiss() { finish(with: nil) }")
        appendLine("    fileprivate var isClaimed: Bool { claimed }")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public typealias BasekitNavigationHandler = @MainActor (BasekitNavigationRequest, BasekitNavigationTransaction) -> Bool")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public typealias BasekitPlatformPresenter = @MainActor (BasekitNavigationEntry, String) -> Void")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        // Kotlin/Native protocols are imported as nonisolated. Keep the generated host's
        // conformance on the main actor instead of suppressing the Swift 6 diagnostic.
        appendLine("@MainActor public final class BasekitNavigationRouter: NSObject, ObservableObject, @MainActor AppleNavigationHost {")
        appendLine("    @Published public private(set) var path: [BasekitNavigationEntry] = []")
        appendLine("    @Published public private(set) var sheet: BasekitNavigationEntry?")
        appendLine("    @Published public private(set) var fullScreenCover: BasekitNavigationEntry?")
        appendLine("    public var platformPresenter: BasekitPlatformPresenter?")
        appendLine("    public var platformDismisser: (@MainActor (UUID) -> Void)?")
        appendLine("    /// Called on the main actor when `close` names an owner this router does not present: the owner of")
        appendLine("    /// its root. Forward it to whatever presented this router (see `init(parent:policy:)`).")
        appendLine("    public var onCloseRoot: (@MainActor (String, Any?) -> Void)?")
        appendLine("    private let policy: BasekitNavigationPolicy")
        appendLine("    private var handlers: [String: (UUID, BasekitNavigationHandler)] = [:]")
        appendLine("    private var responders: [UUID: NavigationResponder] = [:]")
        appendLine("    private var customEntries: [UUID: BasekitNavigationEntry] = [:]")
        appendLine()
        appendLine("    public init(policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy()) { self.policy = policy; super.init() }")
        appendLine("    /// A router for content presented by [parent], such as a modal that has its own stack and sheets.")
        appendLine("    /// Closing this router's root (an owner it does not present) closes that owner's entry in [parent],")
        appendLine("    /// which also resolves its responder, as a swipe-dismiss in [parent] does. Opt in per presentation:")
        appendLine("    /// this decides nothing about how [parent] presents the entry.")
        appendLine("    public convenience init(parent: BasekitNavigationRouter, policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy()) {")
        appendLine("        self.init(policy: policy)")
        appendLine("        onCloseRoot = { [weak parent] ownerID, context in parent?.close(ownerId: ownerID, context: context) }")
        appendLine("    }")
        appendLine("    public func root(_ route: BasekitRoute, ownerID: String = UUID().uuidString) -> BasekitNavigationEntry { .init(ownerID: ownerID, route: route) }")
        appendLine("    /// Opens [route] from outside the graph, such as a deep link. A responding destination opened")
        appendLine("    /// without a responder gets one that discards its result, since nobody is waiting for it; it runs,")
        appendLine("    /// responds and closes as it does when a navigator opens it.")
        appendLine("    public func open(_ route: BasekitRoute, ownerID: String = \"deep-link\") {")
        appendLine("        let responder: NavigationResponder? = Self.lacksResponder(route) ? BasekitDiscardingResponder() : nil")
        appendLine("        if let edge = Self.edge(of: route) {")
        appendLine("            receive(ownerID: ownerID, route: route, edge: edge, context: nil, responder: responder)")
        appendLine("        } else {")
        appendLine("            let entryID = UUID(); path = [.init(id: entryID, route: attach(responder, to: route, entryID: entryID))]")
        appendLine("        }")
        appendLine("    }")
        appendLine("    @discardableResult public func open(args: NavigatorArgs, ownerID: String = \"deep-link\") -> Bool { guard let route = BasekitRoute(args: args) else { return false }; open(route, ownerID: ownerID); return true }")
        appendLine("    @discardableResult public func open(match: RouteMatch, ownerID: String = \"deep-link\") -> Bool { open(args: match.args, ownerID: ownerID) }")
        appendLine()
        appendLine("    public var pathBinding: Binding<[BasekitNavigationEntry]> { Binding(get: { self.path }, set: { self.reconcilePath($0) }) }")
        appendLine("    public var sheetBinding: Binding<BasekitNavigationEntry?> { Binding(get: { self.sheet }, set: { self.replaceModal(&self.sheet, with: $0) }) }")
        appendLine("    public var fullScreenCoverBinding: Binding<BasekitNavigationEntry?> { Binding(get: { self.fullScreenCover }, set: { self.replaceModal(&self.fullScreenCover, with: $0) }) }")
        appendLine()
        appendLine("    @discardableResult public func register(ownerID: String, handler: @escaping BasekitNavigationHandler) -> UUID {")
        appendLine("        let token = UUID(); handlers[ownerID] = (token, handler); return token")
        appendLine("    }")
        appendLine("    public func unregister(ownerID: String, token: UUID) { if handlers[ownerID]?.0 == token { handlers.removeValue(forKey: ownerID) } }")
        appendLine()
        appendLine("    public func close(ownerId: String, context: Any?) {")
        appendLine("        if sheet?.ownerID == ownerId { replaceModal(&sheet, with: nil); return }")
        appendLine("        if fullScreenCover?.ownerID == ownerId { replaceModal(&fullScreenCover, with: nil); return }")
        appendLine("        if let custom = customEntries.values.first(where: { $0.ownerID == ownerId }) { resolve(entryID: custom.id, result: nil, dismiss: true); return }")
        appendLine("        guard let index = path.firstIndex(where: { $0.ownerID == ownerId }) else { onCloseRoot?(ownerId, context); return }")
        appendLine("        let removed = Array(path[index...]); path.removeSubrange(index...); removed.forEach { resolve(entryID: $0.id, result: nil, dismiss: false) }")
        appendLine("    }")
        appendLine("    public func finish(entryID: UUID, with result: Any?) { resolve(entryID: entryID, result: result, dismiss: true) }")
        appendLine("    public func dismiss(entryID: UUID) { resolve(entryID: entryID, result: nil, dismiss: true) }")

        val sitesByTarget = sites.groupBy { it.target.qualifiedName }
        for (targetSites in sitesByTarget.values) {
            val target = targetSites.first().target
            val cap = target.navName.toUpperCamelCase()
            val routeName = target.navName.toSwiftCase()
            val params = buildList {
                add("ownerId: String")
                target.argsSwiftName?.let { add("args: $it") }
                add("edge: AppleNavigationEdge")
                add("context: Any?")
                if (target.responseQualifiedName != null) add("responder: NavigationResponder")
            }.joinToString(", ")
            val routeArgs = buildList {
                target.argsSwiftName?.let { add("args: args") }
                add("edge: nativeEdge")
                if (target.responseQualifiedName != null) add("responder: responder")
            }.joinToString(", ")
            appendLine("    public func show$cap($params) {")
            appendLine("        let nativeEdge = BasekitNavigationEdge(edge)")
            appendLine("        receive(ownerID: ownerId, route: .$routeName($routeArgs), edge: nativeEdge, context: context${if (target.responseQualifiedName != null) ", responder: responder" else ""})")
            appendLine("    }")
        }

        appendLine()
        appendLine("    private func receive(ownerID: String, route: BasekitRoute, edge: BasekitNavigationEdge, context: Any?, responder: NavigationResponder? = nil) {")
        appendLine("        let entryID = UUID(); let routed = attach(responder, to: route, entryID: entryID)")
        appendLine("        let entry = BasekitNavigationEntry(id: entryID, ownerID: UUID().uuidString, route: routed, edge: edge, context: context)")
        appendLine("        let request = BasekitNavigationRequest(ownerID: ownerID, route: routed, edge: edge, context: context)")
        appendLine("        let transaction = BasekitNavigationTransaction(router: self, entry: entry)")
        appendLine("        if handlers[ownerID]?.1(request, transaction) == true {")
        appendLine("            if !transaction.isClaimed { return }")
        appendLine("        } else if !transaction.isClaimed { present(entry, override: policy.decision(for: request)) }")
        appendLine("    }")
        appendLine("    /// [route] with [responder] behind a proxy that resolves once and closes entry [entryID] when the")
        appendLine("    /// destination responds; [route] unchanged when there is no responder.")
        appendLine("    private func attach(_ responder: NavigationResponder?, to route: BasekitRoute, entryID: UUID) -> BasekitRoute {")
        appendLine("        guard let responder else { return route }")
        appendLine("        let proxy = BasekitResponderProxy(upstream: responder) { [weak self] in self?.completeFromDestination(entryID) }")
        appendLine("        responders[entryID] = proxy; return Self.replacingResponder(in: route, with: proxy)")
        appendLine("    }")
        appendLine("    fileprivate func present(_ entry: BasekitNavigationEntry, override: BasekitNavigationDecision?) {")
        appendLine("        var entry = entry; if let override { entry.decision = override }")
        appendLine("        switch entry.decision.presentation {")
        appendLine("        case .push: path.append(entry)")
        appendLine("        case .sheet: replaceModal(&sheet, with: entry)")
        appendLine("        case .fullScreenCover: replaceModal(&fullScreenCover, with: entry)")
        appendLine("        case .platformCustom(let id):")
        appendLine("            if let platformPresenter { customEntries[entry.id] = entry; platformPresenter(entry, id) } else { assertionFailure(\"No Basekit platformPresenter for custom presentation \\(id)\"); resolve(entryID: entry.id, result: nil, dismiss: false) }")
        appendLine("        }")
        appendLine("    }")
        appendLine("    fileprivate func resolve(entryID: UUID, result: Any?, dismiss: Bool) {")
        appendLine("        responders.removeValue(forKey: entryID)?.respond(response: result)")
        appendLine("        guard dismiss else { return }")
        appendLine("        if sheet?.id == entryID { sheet = nil }; if fullScreenCover?.id == entryID { fullScreenCover = nil }")
        appendLine("        if let index = path.firstIndex(where: { $0.id == entryID }) { path.removeSubrange(index...) }")
        appendLine("        if customEntries.removeValue(forKey: entryID) != nil { platformDismisser?(entryID) }")
        appendLine("    }")
        appendLine("    private func completeFromDestination(_ entryID: UUID) {")
        appendLine("        responders.removeValue(forKey: entryID); if sheet?.id == entryID { sheet = nil }; if fullScreenCover?.id == entryID { fullScreenCover = nil }; if let index = path.firstIndex(where: { $0.id == entryID }) { path.removeSubrange(index...) }; if customEntries.removeValue(forKey: entryID) != nil { platformDismisser?(entryID) }")
        appendLine("    }")
        appendLine("    public func reconcilePath(_ newPath: [BasekitNavigationEntry]) {")
        appendLine("        let retained = Set(newPath.map(\\.id)); path.filter { !retained.contains($0.id) }.forEach { resolve(entryID: $0.id, result: nil, dismiss: false) }; path = newPath")
        appendLine("    }")
        appendLine("    private func replaceModal(_ slot: inout BasekitNavigationEntry?, with replacement: BasekitNavigationEntry?) {")
        appendLine("        let removedID = slot?.id != replacement?.id ? slot?.id : nil; slot = replacement; if let removedID { responders.removeValue(forKey: removedID)?.respond(response: nil) }")
        appendLine("    }")
        appendLine("    private static func edge(of route: BasekitRoute) -> BasekitNavigationEdge? {")
        appendLine("        switch route {")
        destinations.forEach { destination ->
            val routeName = destination.navName.toSwiftCase()
            val ignored = buildList {
                if (destination.argsSwiftName != null) add("_")
                add("let edge")
                if (destination.responseQualifiedName != null) add("_")
            }.joinToString(", ")
            appendLine("        case .$routeName($ignored): return edge")
        }
        appendLine("        }")
        appendLine("    }")
        appendLine("    /// Whether [route] is for a responding destination but carries no responder.")
        appendLine("    private static func lacksResponder(_ route: BasekitRoute) -> Bool {")
        val responding = destinations.filter { it.responseQualifiedName != null }
        if (responding.isEmpty()) {
            appendLine("        false")
        } else {
            appendLine("        switch route {")
            responding.forEach { destination ->
                val pattern = buildList {
                    if (destination.argsSwiftName != null) add("_")
                    add("_")
                    add(".none")
                }.joinToString(", ")
                appendLine("        case .${destination.navName.toSwiftCase()}($pattern): return true")
            }
            appendLine("        default: return false")
            appendLine("        }")
        }
        appendLine("    }")
        appendLine("    private static func replacingResponder(in route: BasekitRoute, with responder: NavigationResponder) -> BasekitRoute {")
        if (destinations.any { it.responseQualifiedName != null }) {
            appendLine("        switch route {")
            destinations.filter { it.responseQualifiedName != null }.forEach { destination ->
                val routeName = destination.navName.toSwiftCase()
                val pattern = buildList {
                    if (destination.argsSwiftName != null) add("let args")
                    add("let edge")
                    add("_")
                }.joinToString(", ")
                val values = buildList {
                    if (destination.argsSwiftName != null) add("args: args")
                    add("edge: edge")
                    add("responder: responder")
                }.joinToString(", ")
                appendLine("        case .$routeName($pattern): return .$routeName($values)")
            }
            appendLine("        default: return route")
            appendLine("        }")
        } else {
            appendLine("        return route")
        }
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("private struct BasekitNavigationHandlerModifier: ViewModifier {")
        appendLine("    @ObservedObject var router: BasekitNavigationRouter")
        appendLine("    let ownerID: String; let handler: BasekitNavigationHandler; @State private var token: UUID?")
        appendLine("    func body(content: Content) -> some View { content.onAppear { token = router.register(ownerID: ownerID, handler: handler) }.onDisappear { if let token { router.unregister(ownerID: ownerID, token: token) } } }")
        appendLine("}")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public extension View {")
        appendLine("    func basekitNavigationHandler(router: BasekitNavigationRouter, ownerID: String, _ handler: @escaping BasekitNavigationHandler) -> some View { modifier(BasekitNavigationHandlerModifier(router: router, ownerID: ownerID, handler: handler)) }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public struct BasekitNavigationStackHost<Root: View, Destination: View>: View {")
        appendLine("    @ObservedObject private var router: BasekitNavigationRouter")
        appendLine("    private let rootEntry: BasekitNavigationEntry")
        appendLine("    private let root: (BasekitNavigationEntry, Namespace.ID) -> Root")
        appendLine("    private let destination: (BasekitNavigationEntry, Namespace.ID) -> Destination")
        appendLine("    @Namespace private var namespace")
        appendLine("    public init(router: BasekitNavigationRouter, rootEntry: BasekitNavigationEntry, @ViewBuilder root: @escaping (BasekitNavigationEntry, Namespace.ID) -> Root, @ViewBuilder destination: @escaping (BasekitNavigationEntry, Namespace.ID) -> Destination) { self.router = router; self.rootEntry = rootEntry; self.root = root; self.destination = destination }")
        appendLine("    public var body: some View {")
        appendLine("        NavigationStack(path: router.pathBinding) {")
        appendLine("            root(rootEntry, namespace).navigationDestination(for: BasekitNavigationEntry.self) { entry in transitioned(entry) }")
        appendLine("        }.sheet(item: router.sheetBinding) { transitioned($0) }")
        appendLine("#if canImport(UIKit)")
        appendLine("        .fullScreenCover(item: router.fullScreenCoverBinding) { transitioned($0) }")
        appendLine("#else")
        appendLine("        .sheet(item: router.fullScreenCoverBinding) { transitioned($0) }")
        appendLine("#endif")
        appendLine("    }")
        appendLine("    @ViewBuilder private func transitioned(_ entry: BasekitNavigationEntry) -> some View {")
        appendLine("        switch entry.decision.transition {")
        appendLine("        case .zoom(let sourceID):")
        appendLine("#if canImport(UIKit)")
        appendLine("            destination(entry, namespace).navigationTransition(.zoom(sourceID: sourceID, in: namespace))")
        appendLine("#else")
        appendLine("            destination(entry, namespace).navigationTransition(.automatic)")
        appendLine("#endif")
        appendLine("        case .automatic, .custom: destination(entry, namespace).navigationTransition(.automatic)")
        appendLine("        }")
        appendLine("    }")
        appendLine("}")
        appendLine()

