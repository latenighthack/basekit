package com.latenighthack.basekit.navigation.codegen

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies

/**
 * Emits the app-specific Swift route model, router, interception API, and native renderers.
 *
 * The router carries a `NavigationObserver` and, when [actionObservers] is set (basekit-viewmodel is on
 * the classpath), a `ViewModelActionObserver`: `basekitViewModel` wraps the navigators and view models it
 * builds with them, and the router itself reports the screens it shows or dismisses without a navigator.
 */
class AppleSwiftNavigationGenerator(
    private val codeGenerator: CodeGenerator,
    private val dependencies: Dependencies,
    private val frameworkImports: List<String>,
    private val actionObservers: Boolean = true,
) {
    private data class Site(
        val edge: NavEdge,
        val target: DestinationInfo,
        // kotlinName must match HostedNavigatorGenerator's NavigationEdge entry so the
        // BasekitNavigationEdge(_:) switch stays exhaustive. Both are target-disambiguated on fan-out.
        val kotlinName: String,
        val swiftName: String,
    )

    fun generate(destinations: List<DestinationInfo>, hostedComponents: List<DestinationInfo> = emptyList()) {
        val byName = destinations.associateBy { it.qualifiedName }
        // Hosted components contribute call sites; only destinations are routes.
        val rawSites = (destinations + hostedComponents).flatMap { source ->
            source.edges.mapNotNull { edge -> byName[edge.targetQualifiedName]?.let { edge to it } }
        }.distinctBy { (edge, _) -> edge }
        if (rawSites.isEmpty()) return

        // Kept in lockstep with HostedNavigatorGenerator: a fan-out action (multiple @NavigateTo)
        // produces call sites sharing a source+method base name, so disambiguate by target.
        val colliding = rawSites.groupingBy { (edge, _) -> edge.sourceEntry }
            .eachCount().filterValues { it > 1 }.keys
        val sites = rawSites.map { (edge, target) ->
            val fanOut = edge.sourceEntry in colliding
            val kotlinName = if (fanOut) "${edge.sourceEntry}_TO_${target.navName.uppercase()}" else edge.sourceEntry
            val swiftRaw = if (fanOut) {
                "${edge.sourceNavName}_${edge.methodName}_to_${target.navName}"
            } else {
                "${edge.sourceNavName}_${edge.methodName}"
            }
            Site(edge, target, kotlinName, swiftRaw.toUpperCamelCase().replaceFirstChar { it.lowercase() })
        }
        if (sites.isEmpty()) return

        val content = render(destinations, sites)
        codeGenerator.createNewFile(dependencies, "", "BasekitAppleNavigation", "swift").use {
            it.write(content.encodeToByteArray())
        }
    }

    private fun render(destinations: List<DestinationInfo>, sites: List<Site>): String = buildString {
        frameworkImports.forEach { appendLine("import $it") }
        appendLine("import Foundation")
        appendLine("import Combine")
        appendLine("import SwiftUI")
        appendLine("#if canImport(UIKit)")
        appendLine("import UIKit")
        appendLine("#elseif canImport(AppKit)")
        appendLine("import AppKit")
        appendLine("#endif")
        appendLine()
        appendLine("// Generated by Basekit from the Kotlin navigation graph.")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public enum BasekitNavigationEdge: Hashable {")
        sites.forEach { appendLine("    case ${it.swiftName}") }
        appendLine()
        appendLine("    init(_ edge: NavigationEdge) {")
        appendLine("        switch edge {")
        sites.forEach { appendLine("        case .${it.kotlinName.toSwiftEnumCase()}: self = .${it.swiftName}") }
        appendLine("        }")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public enum BasekitRoute {")
        destinations.forEach { destination ->
            val routeName = destination.navName.toSwiftCase()
            val params = buildList {
                destination.argsSwiftName?.let { add("args: $it") }
                add("edge: BasekitNavigationEdge?")
