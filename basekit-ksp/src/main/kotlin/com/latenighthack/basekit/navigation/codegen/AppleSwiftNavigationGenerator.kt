        appendLine("    @MainActor func decision(for request: BasekitNavigationRequest) -> BasekitNavigationDecision")
        appendLine("}")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public struct BasekitDefaultNavigationPolicy: BasekitNavigationPolicy {")
        appendLine("    public init() {}")
        appendLine("    @MainActor public func decision(for request: BasekitNavigationRequest) -> BasekitNavigationDecision { .init() }")
        appendLine("}")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("private final class BasekitResponderProxy: NSObject, NavigationResponder {")
        appendLine("    private let upstream: NavigationResponder; private let completed: @MainActor () -> Void; private let lock = NSLock(); private var resolved = false")
        appendLine("    init(upstream: NavigationResponder, completed: @escaping @MainActor () -> Void) { self.upstream = upstream; self.completed = completed }")
        appendLine("    func respond(response: Any?) {")
        appendLine("        lock.lock(); guard !resolved else { lock.unlock(); return }; resolved = true; lock.unlock()")
        appendLine("        upstream.respond(response: response); let completion = completed; Task { @MainActor in completion() }")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("/// The responder `open` gives a responding destination reached by a deep link: nobody waits for its")
        appendLine("/// result, so the result is discarded and the destination closes as it would anywhere else.")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("private final class BasekitDiscardingResponder: NSObject, NavigationResponder {")
        appendLine("    func respond(response: Any?) {}")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("@MainActor public final class BasekitNavigationTransaction {")
        appendLine("    private weak var router: BasekitNavigationRouter?")
        appendLine("    fileprivate let entry: BasekitNavigationEntry")
        appendLine("    private var claimed = false")
        appendLine("    fileprivate init(router: BasekitNavigationRouter, entry: BasekitNavigationEntry) { self.router = router; self.entry = entry }")
        appendLine("    public func presentDefault() { guard !claimed else { return }; claimed = true; router?.present(entry, override: nil) }")
        appendLine("    public func present(using decision: BasekitNavigationDecision) { guard !claimed else { return }; claimed = true; router?.present(entry, override: decision) }")
        appendLine("    public func finish(with result: Any?) { guard !claimed else { return }; claimed = true; router?.resolve(entryID: entry.id, result: result, dismiss: true) }")
        appendLine("    public func dismiss() { finish(with: nil) }")
        appendLine("    fileprivate var isClaimed: Bool { claimed }")
        appendLine("}")
        appendLine()
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public typealias BasekitNavigationHandler = @MainActor (BasekitNavigationRequest, BasekitNavigationTransaction) -> Bool")
        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        appendLine("public typealias BasekitPlatformPresenter = @MainActor (BasekitNavigationEntry, String) -> Void")
        appendLine()

        appendLine("@available(iOS 18.0, macOS 15.0, *)")
        // Kotlin/Native protocols are imported as nonisolated. Keep the generated host's
        // conformance on the main actor instead of suppressing the Swift 6 diagnostic.
        appendLine("@MainActor public final class BasekitNavigationRouter: NSObject, ObservableObject, @MainActor NavigationHost {")
        // Each change to what this router presents is compared with what it last reported presented.
        appendLine("    @Published public private(set) var path: [BasekitNavigationEntry] = [] { didSet { syncPresentation() } }")
        appendLine("    @Published public private(set) var sheet: BasekitNavigationEntry? { didSet { syncPresentation() } }")
        appendLine("    @Published public private(set) var fullScreenCover: BasekitNavigationEntry? { didSet { syncPresentation() } }")
        appendLine("    public var platformPresenter: BasekitPlatformPresenter?")
        appendLine("    public var platformDismisser: (@MainActor (UUID) -> Void)?")
        appendLine("    /// Called on the main actor when `close` names an owner this router does not present: the owner of")
        appendLine("    /// its root. Forward it to whatever presented this router (see `init(parent:policy:)`).")
        appendLine("    public var onCloseRoot: (@MainActor (String, Any?) -> Void)?")
        appendLine("    /// Receives the screens this router shows or dismisses without a navigator: a root or other entry")
        appendLine("    /// the host made, a deep link, Back, a swipe or a dragged-down sheet. `basekitViewModel` also wraps")
        appendLine("    /// each navigator it builds with this router in an `Observing…Navigator` reporting to it. The routers")
        appendLine("    /// this one makes, and those made with `init(parent:)`, report to their parent's observers.")
        appendLine("    public let navigationObserver: NavigationObserver")
        if (actionObservers) {
            appendLine("    /// `basekitViewModel` wraps each view model it builds with this router in `Observing…` reporting to it.")
            appendLine("    public let actionObserver: ViewModelActionObserver")
            appendLine("    /// Receives the events of each view model `basekitViewModel` builds with this router, with its bindings,")
            appendLine("    /// children and rows (see `ViewModelObserver`), as well as `actionObserver`. Routers made from this one")
            appendLine("    /// use it unless they set their own.")
            appendLine("    public var viewModelObserver: (any ViewModelObserver)? {")
            appendLine("        get { ownViewModelObserver ?? parentRouter?.viewModelObserver }")
            appendLine("        set { ownViewModelObserver = newValue }")
            appendLine("    }")
            appendLine("    private var ownViewModelObserver: (any ViewModelObserver)?")
        }
        appendLine("    private let policy: BasekitNavigationPolicy")
        appendLine("    private var handlers: [String: (UUID, BasekitNavigationHandler)] = [:]")
        appendLine("    private var responders: [UUID: NavigationResponder] = [:]")
        appendLine("    private var customEntries: [UUID: BasekitNavigationEntry] = [:] { didSet { syncPresentation() } }")
        appendLine("    /// What this router presented as last reported to a `NavigationPresentationObserver`, bottom first.")
        appendLine("    private var presentedEntries: [(id: UUID, entry: BasekitNavigationEntry, presentation: String)] = []")
        appendLine("    private var presentedRoots: Set<UUID> = []")
        appendLine("    /// The router made for each entry this router presents other than by push.")
        appendLine("    private var children: [UUID: BasekitNavigationRouter] = [:]")
        appendLine("    private weak var parentRouter: BasekitNavigationRouter?")
        appendLine("    /// Set once this router's entry has left its parent: it presents nothing more.")
        appendLine("    private var closed = false")
        appendLine("    /// This router's platform presenter, or else its parent's, as it is when used.")
        appendLine("    private var presenter: BasekitPlatformPresenter? { platformPresenter ?? parentRouter?.presenter }")
        appendLine("    private var dismisser: (@MainActor (UUID) -> Void)? { platformDismisser ?? parentRouter?.dismisser }")
        appendLine("    /// The router at the top of this one's tree, which remembers the entries reported shown.")
        appendLine("    private var topRouter: BasekitNavigationRouter { parentRouter?.topRouter ?? self }")
        appendLine("    /// The entries without an edge (roots, deep links) whose showing this tree has reported.")
        appendLine("    private var reportedEntryIDs: Set<UUID> = []")
        appendLine()
        if (actionObservers) {
            appendLine("    public init(")
            appendLine("        policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy(),")
            appendLine("        navigationObserver: NavigationObserver = NavigationObserverCompanion.shared.NoOp,")
            appendLine("        actionObserver: ViewModelActionObserver = ViewModelActionObserverCompanion.shared.NoOp")
            appendLine("    ) {")
            appendLine("        self.policy = policy; self.navigationObserver = navigationObserver; self.actionObserver = actionObserver; super.init()")
            appendLine("    }")
        } else {
            appendLine("    public init(policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy(), navigationObserver: NavigationObserver = NavigationObserverCompanion.shared.NoOp) {")
            appendLine("        self.policy = policy; self.navigationObserver = navigationObserver; super.init()")
            appendLine("    }")
        }
        appendLine("    /// A router for content presented by [parent], such as a modal that has its own stack and sheets.")
        appendLine("    /// Closing this router's root (an owner it does not present) closes that owner's entry in [parent],")
        appendLine("    /// which also resolves its responder, as a swipe-dismiss in [parent] does. Without a platform presenter")
        appendLine("    /// or dismisser of its own it uses [parent]'s, and it reports to [parent]'s observers. This decides")
        appendLine("    /// nothing about how [parent] presents the entry. [parent] makes one for each entry it presents other")
        appendLine("    /// than by push; see `host(for:)`.")
        appendLine("    public convenience init(parent: BasekitNavigationRouter, policy: BasekitNavigationPolicy = BasekitDefaultNavigationPolicy()) {")
        if (actionObservers) {
            appendLine("        self.init(policy: policy, navigationObserver: parent.navigationObserver, actionObserver: parent.actionObserver)")
        } else {
            appendLine("        self.init(policy: policy, navigationObserver: parent.navigationObserver)")
        }
        appendLine("        parentRouter = parent")
        appendLine("        onCloseRoot = { [weak parent] ownerID, context in parent?.close(ownerId: ownerID, context: context) }")
        appendLine("    }")
        appendLine("    public func root(_ route: BasekitRoute, ownerID: String = UUID().uuidString) -> BasekitNavigationEntry { .init(ownerID: ownerID, route: route) }")
        appendLine("    /// The router [entry]'s navigator reports to: build the entry's view model with it as `host`. For an")
        appendLine("    /// entry this router, or a router it made, presents as a sheet, cover or custom presentation, that is")
        appendLine("    /// the router made for the entry, so what the entry opens is presented from it, over the entry. For a")
        appendLine("    /// pushed entry it is the router whose path holds it; otherwise this router.")
        appendLine("    public func host(for entry: BasekitNavigationEntry) -> BasekitNavigationRouter { router(holding: entry) ?? self }")
        appendLine("    /// Opens [route] from outside the graph, such as a deep link. A responding destination opened")
        appendLine("    /// without a responder gets one that discards its result, since nobody is waiting for it; it runs,")
        appendLine("    /// responds and closes as it does when a navigator opens it. It is reported to `navigationObserver`")
        appendLine("    /// as a `NavigatedTo` before it is presented.")
        appendLine("    public func open(_ route: BasekitRoute, ownerID: String = \"deep-link\") {")
        appendLine("        let responder: NavigationResponder? = Self.lacksResponder(route) ? BasekitDiscardingResponder() : nil")
        appendLine("        if !closed { reportShown(route) }")
        appendLine("        if let edge = Self.edge(of: route) {")
        appendLine("            receive(ownerID: ownerID, route: route, edge: edge, context: nil, responder: responder)")
        appendLine("        } else {")
        appendLine("            let entryID = UUID(); topRouter.reportedEntryIDs.insert(entryID)")
        appendLine("            path = [.init(id: entryID, route: attach(responder, to: route, entryID: entryID))]")
        appendLine("        }")
        appendLine("    }")
        appendLine("    @discardableResult public func open(args: NavigatorArgs, ownerID: String = \"deep-link\") -> Bool { guard let route = BasekitRoute(args: args) else { return false }; open(route, ownerID: ownerID); return true }")
        appendLine("    @discardableResult public func open(match: RouteMatch, ownerID: String = \"deep-link\") -> Bool { open(args: match.args, ownerID: ownerID) }")
        appendLine()
        appendLine("    /// Reports [entry] shown, once, when neither a navigator nor `open` opened it: a root, or an entry the")
        appendLine("    /// host made itself. `BasekitDestinationView` and the stack hosts call it as an entry appears; a host")
        appendLine("    /// that shows entries its own way calls it too. An entry a navigator opened has an edge and was")
        appendLine("    /// reported by its `Observing…Navigator`, so it is not reported again.")
        appendLine("    public func didShow(_ entry: BasekitNavigationEntry) {")
        appendLine("        if !closed, let observer = navigationObserver as? NavigationPresentationObserver,")
        appendLine("           !presentedEntries.contains(where: { $0.id == entry.id }), presentedRoots.insert(entry.id).inserted {")
        appendLine("            observer.onPresentation(event: HostNavigationEvents.shared.presented(screen: Self.screen(of: entry.route), entryId: entry.id.uuidString, presentation: \"ROOT\", customId: nil))")
        appendLine("        }")
        appendLine("        guard !closed, entry.edge == nil, topRouter.reportedEntryIDs.insert(entry.id).inserted else { return }")
        appendLine("        reportShown(entry.route)")
        appendLine("    }")
        appendLine()
        appendLine("    /// The stack, sheet and cover as the host shows them. A host-driven change (Back, a swipe, a dragged-down")
        appendLine("    /// sheet) reports each entry it removes closed; one that matches the router's own state reports nothing.")
        appendLine("    public var pathBinding: Binding<[BasekitNavigationEntry]> { Binding(get: { self.path }, set: { self.reconcilePath($0) }) }")
        appendLine("    public var sheetBinding: Binding<BasekitNavigationEntry?> {")
        appendLine("        Binding(get: { self.sheet }, set: { replacement in")
        appendLine("            if let removed = self.sheet, removed.id != replacement?.id { self.reportClosed([removed]) }")
        appendLine("            self.replaceModal(&self.sheet, with: replacement)")
        appendLine("        })")
        appendLine("    }")
        appendLine("    public var fullScreenCoverBinding: Binding<BasekitNavigationEntry?> {")
        appendLine("        Binding(get: { self.fullScreenCover }, set: { replacement in")
        appendLine("            if let removed = self.fullScreenCover, removed.id != replacement?.id { self.reportClosed([removed]) }")
        appendLine("            self.replaceModal(&self.fullScreenCover, with: replacement)")
        appendLine("        })")
        appendLine("    }")
        appendLine()
        appendLine("    @discardableResult public func register(ownerID: String, handler: @escaping BasekitNavigationHandler) -> UUID {")
        appendLine("        let token = UUID(); handlers[ownerID] = (token, handler); return token")
        appendLine("    }")
        appendLine("    public func unregister(ownerID: String, token: UUID) { if handlers[ownerID]?.0 == token { handlers.removeValue(forKey: ownerID) } }")
        appendLine()
        appendLine("    public func close(ownerId: String, context: Any?) {")
        appendLine("        if sheet?.ownerID == ownerId { replaceModal(&sheet, with: nil); return }")
        appendLine("        if fullScreenCover?.ownerID == ownerId { replaceModal(&fullScreenCover, with: nil); return }")
        appendLine("        if let custom = customEntries.values.first(where: { $0.ownerID == ownerId }) { resolve(entryID: custom.id, result: nil, dismiss: true); return }")
        appendLine("        guard let index = path.firstIndex(where: { $0.ownerID == ownerId }) else { onCloseRoot?(ownerId, context); return }")
        appendLine("        let removed = Array(path[index...]); path.removeSubrange(index...); removed.forEach { resolve(entryID: $0.id, result: nil, dismiss: false) }")
        appendLine("    }")
        appendLine("    /// Finishes or dismisses entry [entryID] for the host, such as a custom presentation it dismissed: the")
        appendLine("    /// entries it removes are reported closed.")
        appendLine("    public func finish(entryID: UUID, with result: Any?) { reportClosed(presented(removedBy: entryID)); resolve(entryID: entryID, result: result, dismiss: true) }")
        appendLine("    public func dismiss(entryID: UUID) { reportClosed(presented(removedBy: entryID)); resolve(entryID: entryID, result: nil, dismiss: true) }")

        val sitesByTarget = sites.groupBy { it.target.qualifiedName }
        for (targetSites in sitesByTarget.values) {
            val target = targetSites.first().target
            val cap = target.navName.toUpperCamelCase()
            val routeName = target.navName.toSwiftCase()
            val params = buildList {
                add("ownerId: String")
                target.argsSwiftName?.let { add("args: $it") }
                add("edge: NavigationEdge")
                add("context: Any?")
                if (target.responseQualifiedName != null) add("responder: NavigationResponder")
            }.joinToString(", ")
            val routeArgs = buildList {
                target.argsSwiftName?.let { add("args: args") }
                add("edge: nativeEdge")
                if (target.responseQualifiedName != null) add("responder: responder")
            }.joinToString(", ")
            appendLine("    public func show$cap($params) {")
            appendLine("        let nativeEdge = BasekitNavigationEdge(edge)")
            appendLine("        receive(ownerID: ownerId, route: .$routeName($routeArgs), edge: nativeEdge, context: context${if (target.responseQualifiedName != null) ", responder: responder" else ""})")
            appendLine("    }")
        }

        appendLine()
        appendLine("    private func receive(ownerID: String, route: BasekitRoute, edge: BasekitNavigationEdge, context: Any?, responder: NavigationResponder? = nil) {")
        appendLine("        // A dismissed entry's view model can still navigate; nothing shows this router any more.")
        appendLine("        if closed { responder?.respond(response: nil); return }")
        appendLine("        let entryID = UUID(); let routed = attach(responder, to: route, entryID: entryID)")
        appendLine("        let entry = BasekitNavigationEntry(id: entryID, ownerID: UUID().uuidString, route: routed, edge: edge, context: context)")
        appendLine("        let request = BasekitNavigationRequest(ownerID: ownerID, route: routed, edge: edge, context: context)")
        appendLine("        let transaction = BasekitNavigationTransaction(router: self, entry: entry)")
        appendLine("        if handlers[ownerID]?.1(request, transaction) == true {")
        appendLine("            if !transaction.isClaimed { return }")
        appendLine("        } else if !transaction.isClaimed { present(entry, override: policy.decision(for: request)) }")
        appendLine("    }")
        appendLine("    /// [route] with [responder] behind a proxy that resolves once and closes entry [entryID] when the")
        appendLine("    /// destination responds; [route] unchanged when there is no responder.")
        appendLine("    private func attach(_ responder: NavigationResponder?, to route: BasekitRoute, entryID: UUID) -> BasekitRoute {")
        appendLine("        guard let responder else { return route }")
        appendLine("        let proxy = BasekitResponderProxy(upstream: responder) { [weak self] in self?.completeFromDestination(entryID) }")
        appendLine("        responders[entryID] = proxy; return Self.replacingResponder(in: route, with: proxy)")
        appendLine("    }")
        appendLine("    fileprivate func present(_ entry: BasekitNavigationEntry, override: BasekitNavigationDecision?) {")
        appendLine("        var entry = entry; if let override { entry.decision = override }")
        appendLine("        switch entry.decision.presentation {")
        appendLine("        case .push: path.append(entry)")
        appendLine("        case .sheet: replaceModal(&sheet, with: entry)")
        appendLine("        case .fullScreenCover: replaceModal(&fullScreenCover, with: entry)")
        appendLine("        case .platformCustom(let id):")
        appendLine("            if let presenter { adopt(entry); customEntries[entry.id] = entry; presenter(entry, id) } else { assertionFailure(\"No Basekit platformPresenter for custom presentation \\(id)\"); resolve(entryID: entry.id, result: nil, dismiss: false) }")
        appendLine("        }")
        appendLine("    }")
        appendLine("    fileprivate func resolve(entryID: UUID, result: Any?, dismiss: Bool) {")
        appendLine("        responders.removeValue(forKey: entryID)?.respond(response: result)")
        appendLine("        guard dismiss else { return }")
        appendLine("        if sheet?.id == entryID { sheet = nil }; if fullScreenCover?.id == entryID { fullScreenCover = nil }")
        appendLine("        if let index = path.firstIndex(where: { $0.id == entryID }) { path.removeSubrange(index...) }")
        appendLine("        if customEntries.removeValue(forKey: entryID) != nil { dismisser?(entryID) }")
        appendLine("        dropChild(entryID)")
        appendLine("    }")
        appendLine("    private func completeFromDestination(_ entryID: UUID) {")
        appendLine("        responders.removeValue(forKey: entryID); if sheet?.id == entryID { sheet = nil }; if fullScreenCover?.id == entryID { fullScreenCover = nil }; if let index = path.firstIndex(where: { $0.id == entryID }) { path.removeSubrange(index...) }; if customEntries.removeValue(forKey: entryID) != nil { dismisser?(entryID) }")
        appendLine("        dropChild(entryID)")
        appendLine("    }")
        appendLine("    /// Makes the router [entry]'s navigator reports to, unless it has one: it presents with this router's")
        appendLine("    /// policy and platform presenter.")
        appendLine("    private func adopt(_ entry: BasekitNavigationEntry) {")
        appendLine("        if children[entry.id] == nil { children[entry.id] = BasekitNavigationRouter(parent: self, policy: policy) }")
        appendLine("    }")
        appendLine("    /// Removes the router made for [entryID], which left this router, with everything it presents.")
        appendLine("    private func dropChild(_ entryID: UUID) { children.removeValue(forKey: entryID)?.tearDown() }")
        appendLine("    /// Empties this router, whose entry left its parent: everything it presents goes, top first, and each")
        appendLine("    /// responder still waiting answers nil.")
        appendLine("    private func tearDown() {")
        appendLine("        closed = true")
        appendLine("        let nested = Array(children.values); children.removeAll(); nested.forEach { $0.tearDown() }")
        appendLine("        Array(responders.keys).forEach { responders.removeValue(forKey: $0)?.respond(response: nil) }")
        appendLine("        sheet = nil; fullScreenCover = nil; path = []")
        appendLine("        let custom = Array(customEntries.keys); customEntries.removeAll(); custom.forEach { dismisser?($0) }")
        appendLine("    }")
        appendLine("    private func router(holding entry: BasekitNavigationEntry) -> BasekitNavigationRouter? {")
        appendLine("        if let child = children[entry.id] { return child }")
        appendLine("        if path.contains(where: { $0.id == entry.id }) { return self }")
        appendLine("        for child in children.values { if let found = child.router(holding: entry) { return found } }")
        appendLine("        return nil")
        appendLine("    }")
        appendLine("    /// Sets the path as the host shows it, such as after Back or a swipe. Each entry it removes is reported")
        appendLine("    /// closed, top first, and its responder answers nil.")
        appendLine("    public func reconcilePath(_ newPath: [BasekitNavigationEntry]) {")
        appendLine("        let retained = Set(newPath.map(\\.id)); let removed = path.filter { !retained.contains($0.id) }")
        appendLine("        reportClosed(removed.reversed()); removed.forEach { resolve(entryID: $0.id, result: nil, dismiss: false) }; path = newPath")
        appendLine("    }")
        appendLine("    /// The entries that leave when entry [entryID] is dismissed, top first: it and, on the path, those over it.")
        appendLine("    private func presented(removedBy entryID: UUID) -> [BasekitNavigationEntry] {")
        appendLine("        if let sheet, sheet.id == entryID { return [sheet] }")
        appendLine("        if let fullScreenCover, fullScreenCover.id == entryID { return [fullScreenCover] }")
        appendLine("        if let custom = customEntries[entryID] { return [custom] }")
        appendLine("        if let index = path.firstIndex(where: { $0.id == entryID }) { return Array(path[index...].reversed()) }")
        appendLine("        return []")
        appendLine("    }")
        appendLine("    /// Reports to the navigation observer, when it is a `NavigationPresentationObserver`, the entries that")
        appendLine("    /// left since the last call, top first, then those that arrived, bottom first.")
        appendLine("    private func syncPresentation() {")
        appendLine("        guard let observer = navigationObserver as? NavigationPresentationObserver else { return }")
        appendLine("        var current: [(id: UUID, entry: BasekitNavigationEntry, presentation: String)] = path.map { ($0.id, $0, \"PUSH\") }")
        appendLine("        current += customEntries.values.map { ($0.id, $0, \"CUSTOM\") }")
        appendLine("        if let sheet { current.append((sheet.id, sheet, \"SHEET\")) }")
        appendLine("        if let fullScreenCover { current.append((fullScreenCover.id, fullScreenCover, \"FULL_SCREEN_COVER\")) }")
        appendLine("        let currentIDs = Set(current.map(\\.id))")
        appendLine("        for left in presentedEntries.reversed() where !currentIDs.contains(left.id) {")
        appendLine("            observer.onPresentation(event: HostNavigationEvents.shared.dismissed(screen: Self.screen(of: left.entry.route), entryId: left.id.uuidString, presentation: left.presentation))")
        appendLine("        }")
        appendLine("        let previousIDs = Set(presentedEntries.map(\\.id))")
        appendLine("        presentedEntries.removeAll { !currentIDs.contains($0.id) }")
        appendLine("        for arrived in current where !previousIDs.contains(arrived.id) {")
        appendLine("            presentedEntries.append(arrived)")
        appendLine("            var customID: String? = nil")
        appendLine("            if case .platformCustom(let id) = arrived.entry.decision.presentation { customID = id }")
        appendLine("            observer.onPresentation(event: HostNavigationEvents.shared.presented(screen: Self.screen(of: arrived.entry.route), entryId: arrived.id.uuidString, presentation: arrived.presentation, customId: customID))")
        appendLine("        }")
        appendLine("    }")
        appendLine("    private func reportShown(_ route: BasekitRoute) {")
        appendLine("        navigationObserver.onNavigation(event: HostNavigationEvents.shared.navigatedTo(screen: Self.screen(of: route), args: Self.args(of: route)))")
        appendLine("    }")
        appendLine("    private func reportClosed(_ entries: [BasekitNavigationEntry]) {")
        appendLine("        entries.forEach { navigationObserver.onNavigation(event: HostNavigationEvents.shared.closed(screen: Self.screen(of: $0.route))) }")
        appendLine("    }")
        appendLine("    private func replaceModal(_ slot: inout BasekitNavigationEntry?, with replacement: BasekitNavigationEntry?) {")
        appendLine("        let removedID = slot?.id != replacement?.id ? slot?.id : nil; if let replacement { adopt(replacement) }; slot = replacement")
        appendLine("        if let removedID { responders.removeValue(forKey: removedID)?.respond(response: nil); dropChild(removedID) }")
        appendLine("    }")
        appendLine("    private static func edge(of route: BasekitRoute) -> BasekitNavigationEdge? {")
        appendLine("        switch route {")
        destinations.forEach { destination ->
            val routeName = destination.navName.toSwiftCase()
            val ignored = buildList {
                if (destination.argsSwiftName != null) add("_")
                add("let edge")
                if (destination.responseQualifiedName != null) add("_")
            }.joinToString(", ")
            appendLine("        case .$routeName($ignored): return edge")
        }
        appendLine("        }")
        appendLine("    }")
        appendLine("    private static func screen(of route: BasekitRoute) -> NavigationScreen {")
        appendLine("        switch route {")
        destinations.forEach { destination ->
            appendLine("        case .${destination.navName.toSwiftCase()}: return .${destination.screenName.toSwiftEnumCase()}")
        }
        appendLine("        }")
        appendLine("    }")
        appendLine("    private static func args(of route: BasekitRoute) -> NavigatorArgs? {")
        appendLine("        switch route {")
        destinations.forEach { destination ->
            val routeName = destination.navName.toSwiftCase()
            if (destination.argsSwiftName == null) {
                appendLine("        case .$routeName: return nil")
            } else {
                val pattern = buildList {
                    add("let args")
                    add("_")
                    if (destination.responseQualifiedName != null) add("_")
                }.joinToString(", ")
                appendLine("        case .$routeName($pattern): return args")
            }
        }
        appendLine("        }")
        appendLine("    }")
        appendLine("    /// Whether [route] is for a responding destination but carries no responder.")
        appendLine("    private static func lacksResponder(_ route: BasekitRoute) -> Bool {")
        val responding = destinations.filter { it.responseQualifiedName != null }
        if (responding.isEmpty()) {
            appendLine("        false")
        } else {
            appendLine("        switch route {")
            responding.forEach { destination ->
                val pattern = buildList {
                    if (destination.argsSwiftName != null) add("_")
                    add("_")
                    add(".none")
                }.joinToString(", ")
                appendLine("        case .${destination.navName.toSwiftCase()}($pattern): return true")
            }
            appendLine("        default: return false")
            appendLine("        }")
        }
        appendLine("    }")
        appendLine("    private static func replacingResponder(in route: BasekitRoute, with responder: NavigationResponder) -> BasekitRoute {")
        if (destinations.any { it.responseQualifiedName != null }) {
            appendLine("        switch route {")
            destinations.filter { it.responseQualifiedName != null }.forEach { destination ->
                val routeName = destination.navName.toSwiftCase()
                val pattern = buildList {
                    if (destination.argsSwiftName != null) add("let args")
                    add("let edge")
                    add("_")
                }.joinToString(", ")
                val values = buildList {
                    if (destination.argsSwiftName != null) add("args: args")
                    add("edge: edge")
                    add("responder: responder")
                }.joinToString(", ")
                appendLine("        case .$routeName($pattern): return .$routeName($values)")
            }
            appendLine("        default: return route")
            appendLine("        }")
        } else {
            appendLine("        return route")
        }
        appendLine("    }")
        appendLine("}")
