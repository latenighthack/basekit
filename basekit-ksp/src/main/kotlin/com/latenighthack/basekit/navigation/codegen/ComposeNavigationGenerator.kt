        appendLine("    private fun routerHolding(entry: BasekitNavigationEntry): BasekitNavigationRouter? {")
        appendLine("        children[entry.id]?.let { return it }")
        appendLine("        if (pathEntries.any { it.id == entry.id }) return this")
        appendLine("        children.values.forEach { child -> child.routerHolding(entry)?.let { return it } }")
        appendLine("        return null")
        appendLine("    }")
        appendLine("    /** Sets the path as the host shows it, such as after system back. Each entry it removes is reported")
        appendLine("     * closed, top first, and its responder answers null. */")
        appendLine("    public fun reconcilePath(newPath: List<BasekitNavigationEntry>) {")
        appendLine("        val retained = newPath.map { it.id }.toSet(); val removed = pathEntries.filter { it.id !in retained }")
        appendLine("        reportClosed(removed.asReversed()); removed.forEach { resolve(it.id, null, dismiss = false) }; replacePath(newPath)")
        appendLine("    }")
        appendLine("    /** The entries that leave when entry [entryId] is dismissed, top first: it and, on the path, those over it. */")
        appendLine("    private fun presentedRemovedBy(entryId: UUID): List<BasekitNavigationEntry> {")
        appendLine("        sheet?.takeIf { it.id == entryId }?.let { return listOf(it) }")
        appendLine("        fullScreenCover?.takeIf { it.id == entryId }?.let { return listOf(it) }")
        appendLine("        customEntries[entryId]?.let { return listOf(it) }")
        appendLine("        val index = pathEntries.indexOfFirst { it.id == entryId }")
        appendLine("        return if (index < 0) emptyList() else pathEntries.subList(index, pathEntries.size).toList().asReversed()")
        appendLine("    }")
        appendLine("    private fun reportShown(route: BasekitRoute) {")
        appendLine("        navigationObserver.onNavigation(HostNavigationEvents.navigatedTo(screen(route), args(route)))")
        appendLine("    }")
        appendLine("    private fun reportClosed(entries: List<BasekitNavigationEntry>) {")
        appendLine("        entries.forEach { navigationObserver.onNavigation(HostNavigationEvents.closed(screen(it.route))) }")
        appendLine("    }")
        appendLine("    private fun screen(route: BasekitRoute): NavigationScreen = when (route) {")
        destinations.forEach { destination ->
            appendLine("        is BasekitRoute.${destination.routeClass} -> NavigationScreen.${destination.screenName}")
        }
        appendLine("    }")
        appendLine("    private fun args(route: BasekitRoute): NavigatorArgs? = when (route) {")
        destinations.forEach { destination ->
            val value = if (destination.argsQualifiedName != null) "route.args" else "null"
            appendLine("        is BasekitRoute.${destination.routeClass} -> $value")
        }
        appendLine("    }")
        appendLine("    private fun replacePath(newPath: List<BasekitNavigationEntry>) { pathEntries.clear(); pathEntries.addAll(newPath); syncPresentation() }")
        appendLine("    private fun removeFrom(index: Int) { pathEntries.subList(index, pathEntries.size).clear(); syncPresentation() }")
        appendLine("    /** Reports to [presentationObserver] the entries that left since the last call, top first, then")
        appendLine("     * those that arrived, bottom first. Nothing is tracked without one. */")
        appendLine("    private fun syncPresentation() {")
        appendLine("        val observer = presentationObserver ?: return")
        appendLine("        val current = LinkedHashMap<UUID, Pair<BasekitNavigationEntry, NavigationPresentation>>()")
        appendLine("        pathEntries.forEach { current[it.id] = it to NavigationPresentation.PUSH }")
        appendLine("        customEntries.values.forEach { current[it.id] = it to NavigationPresentation.CUSTOM }")
        appendLine("        sheet?.let { current[it.id] = it to NavigationPresentation.SHEET }")
        appendLine("        fullScreenCover?.let { current[it.id] = it to NavigationPresentation.FULL_SCREEN_COVER }")
        appendLine("        presentedEntries.keys.filter { it !in current }.asReversed().forEach { id ->")
        appendLine("            val (entry, presentation) = presentedEntries.remove(id) ?: return@forEach")
        appendLine("            observer.onPresentation(HostNavigationEvents.dismissed(screen(entry.route), id.toString(), presentation.name))")
        appendLine("        }")
        appendLine("        current.forEach { (id, presented) ->")
        appendLine("            if (id in presentedEntries) return@forEach")
        appendLine("            presentedEntries[id] = presented")
        appendLine("            val (entry, presentation) = presented")
        appendLine("            val customId = (entry.decision.presentation as? BasekitPresentation.PlatformCustom)?.id")
        appendLine("            observer.onPresentation(HostNavigationEvents.presented(screen(entry.route), id.toString(), presentation.name, customId))")
        appendLine("        }")
        appendLine("    }")
        appendLine("    private fun replaceSheet(replacement: BasekitNavigationEntry?) {")
        appendLine("        val removedId = if (sheet?.id != replacement?.id) sheet?.id else null; replacement?.let { adopt(it) }; sheet = replacement")
        appendLine("        syncPresentation(); removedId?.let { respondNull(it); dropChild(it) }")
        appendLine("    }")
        appendLine("    private fun replaceFullScreenCover(replacement: BasekitNavigationEntry?) {")
        appendLine("        val removedId = if (fullScreenCover?.id != replacement?.id) fullScreenCover?.id else null; replacement?.let { adopt(it) }; fullScreenCover = replacement")
        appendLine("        syncPresentation(); removedId?.let { respondNull(it); dropChild(it) }")
        appendLine("    }")
        appendLine("    private fun respondNull(entryId: UUID) {")
        appendLine("        @Suppress(\"UNCHECKED_CAST\")")
        appendLine("        (responders.remove(entryId) as NavigationResponder<Any>?)?.respond(null)")
        appendLine("    }")
        appendLine("    /** Whether [route] is for a responding destination but carries no responder. */")
        appendLine("    private fun lacksResponder(route: BasekitRoute): Boolean = when (route) {")
        destinations.filter { it.responseQualifiedName != null }.forEach { destination ->
            appendLine("        is BasekitRoute.${destination.routeClass} -> route.responder == null")
        }
        appendLine("        else -> false")
        appendLine("    }")
        appendLine("    @Suppress(\"UNCHECKED_CAST\")")
        appendLine("    private fun replacingResponder(route: BasekitRoute, responder: NavigationResponder<Any>): BasekitRoute = when (route) {")
        destinations.filter { it.responseQualifiedName != null }.forEach { destination ->
            val values = buildList {
                if (destination.argsQualifiedName != null) add("route.args")
                add("route.edge")
                add("responder as NavigationResponder<${destination.responseQualifiedName}>")
            }.joinToString(", ")
            appendLine("        is BasekitRoute.${destination.routeClass} -> BasekitRoute.${destination.routeClass}($values)")
        }
        appendLine("        else -> route")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("/** Registers [handler] for [ownerId] on [router] while this is in the composition. */")
        appendLine("@Composable")
        appendLine("public fun BasekitNavigationHandler(router: BasekitNavigationRouter, ownerId: String, handler: BasekitNavigationHandler) {")
        appendLine("    val current by rememberUpdatedState(handler)")
        appendLine("    DisposableEffect(router, ownerId) {")
        appendLine("        val token = router.register(ownerId) { request, transaction -> current(request, transaction) }")
        appendLine("        onDispose { router.unregister(ownerId, token) }")
        appendLine("    }")
        appendLine("}")
        appendLine()

        appendLine("/**")
        appendLine(" * The router's stack with its sheet and full-screen cover, as a navigation stack shows them. Every")
        appendLine(" * entry on the stack stays composed, the ones under the top hidden, so a screen and its view model")
        appendLine(" * outlive the screens pushed over it. A pushed entry slides in from the end and a popped one out;")
        appendLine(" * system back pops the top entry. [transition] places an entry from its progress, 0 shown to 1 off")
        appendLine(" * screen, for a host that moves screens its own way. [sheet] and [fullScreenCover] present the")
        appendLine(" * router's sheet and cover, a dialog unless the host presents them its own way; `dismiss` closes")
        appendLine(" * them as a swipe or back does.")
        appendLine(" *")
        appendLine(" * [root] and [destination] get each entry with the router its navigator reports to, the `host` to")
        appendLine(" * build its view model with. A sheet or cover shows a stack of its own for the router made for its")
        appendLine(" * entry (see [BasekitNavigationRouter.host]), with the entry at its root, so what it opens is")
        appendLine(" * presented over it, and the sheets it opens stack.")
        appendLine(" */")
        appendLine("@Composable")
        appendLine("public fun BasekitNavigationStackHost(")
        appendLine("    router: BasekitNavigationRouter,")
        appendLine("    rootEntry: BasekitNavigationEntry,")
        appendLine("    modifier: Modifier = Modifier,")
        appendLine("    transition: (BasekitNavigationEntry) -> BasekitStackTransition = { BasekitStackTransition.Slide },")
        appendLine("    root: @Composable (BasekitNavigationEntry, BasekitNavigationRouter) -> Unit,")
        appendLine("    destination: @Composable (BasekitNavigationEntry, BasekitNavigationRouter) -> Unit,")
        appendLine("    sheet: @Composable (BasekitNavigationEntry, dismiss: () -> Unit, content: @Composable () -> Unit) -> Unit = { _, dismiss, content ->")
        appendLine("        Dialog(onDismissRequest = dismiss) { content() }")
        appendLine("    },")
        appendLine("    fullScreenCover: @Composable (BasekitNavigationEntry, dismiss: () -> Unit, content: @Composable () -> Unit) -> Unit = { _, dismiss, content ->")
        appendLine("        Dialog(onDismissRequest = dismiss, properties = DialogProperties(usePlatformDefaultWidth = false)) { Box(Modifier.fillMaxSize()) { content() } }")
        appendLine("    },")
        appendLine(") {")
        appendLine("    BasekitStack(router, rootEntry, modifier, fillRoot = true, transition, root, destination, sheet, fullScreenCover)")
        appendLine("}")
        appendLine()
        appendLine("/** [BasekitNavigationStackHost]'s stack. A presented entry's stack ([fillRoot] false) sizes to its")
        appendLine(" * entries' content, so a dialog stays the size of what it shows. */")
        appendLine("@Composable")
        appendLine("private fun BasekitStack(")
        appendLine("    router: BasekitNavigationRouter,")
        appendLine("    rootEntry: BasekitNavigationEntry,")
        appendLine("    modifier: Modifier,")
        appendLine("    fillRoot: Boolean,")
        appendLine("    transition: (BasekitNavigationEntry) -> BasekitStackTransition,")
        appendLine("    root: @Composable (BasekitNavigationEntry, BasekitNavigationRouter) -> Unit,")
        appendLine("    destination: @Composable (BasekitNavigationEntry, BasekitNavigationRouter) -> Unit,")
        appendLine("    sheet: @Composable (BasekitNavigationEntry, dismiss: () -> Unit, content: @Composable () -> Unit) -> Unit,")
        appendLine("    fullScreenCover: @Composable (BasekitNavigationEntry, dismiss: () -> Unit, content: @Composable () -> Unit) -> Unit,")
        appendLine(") {")
        appendLine("    val shown = remember { mutableStateListOf<BasekitNavigationEntry>() }")
        appendLine("    val leaving = remember { mutableStateListOf<BasekitNavigationEntry>() }")
        appendLine("    val path = router.path")
        appendLine("    // Entries that left the path stay on screen until they've slid out.")
        appendLine("    shown.filter { it !in path && it !in leaving }.forEach { leaving.add(it) }")
        appendLine("    shown.retainAll { it in path || it in leaving }")
        appendLine("    path.filter { it !in shown }.forEach { shown.add(it) }")
        appendLine("    BackHandler(enabled = path.isNotEmpty()) { router.reconcilePath(path.dropLast(1)) }")
        appendLine("    val layoutDirection = LocalLayoutDirection.current")
        appendLine("    // The top entry, the one under it (seen while the top slides) and any sliding out show; the rest")
        appendLine("    // stay composed but hidden.")
        appendLine("    val stack = listOf(rootEntry) + shown")
        appendLine("    val topIndex = stack.indexOfLast { it !in leaving }")
        appendLine("    Box(modifier) {")
        appendLine("        stack.forEachIndexed { index, entry ->")
        appendLine("            key(entry.id) {")
        appendLine("                val isRoot = index == 0")
        appendLine("                LaunchedEffect(Unit) { router.didShow(entry) }")
        appendLine("                val isLeaving = entry in leaving")
        appendLine("                val progress = remember { Animatable(if (isRoot) 0f else 1f) }")
        appendLine("                if (!isRoot) {")
        appendLine("                    LaunchedEffect(isLeaving) {")
        appendLine("                        progress.animateTo(if (isLeaving) 1f else 0f, transition(entry).animationSpec)")
        appendLine("                        if (isLeaving) { leaving.remove(entry); shown.remove(entry) }")
        appendLine("                    }")
        appendLine("                }")
        appendLine("                val visible = isLeaving || index >= topIndex - 1")
        appendLine("                val style = if (isRoot) BasekitStackTransition.None else transition(entry)")
        appendLine("                val sizing = if (fillRoot) Modifier.fillMaxSize() else Modifier")
        appendLine("                Box(")
        appendLine("                    sizing.graphicsLayer {")
        appendLine("                        alpha = if (visible) style.alpha(progress.value) else 0f")
        appendLine("                        val direction = if (layoutDirection == LayoutDirection.Ltr) 1f else -1f")
        appendLine("                        translationX = style.offset(progress.value) * size.width * direction")
        appendLine("                    },")
        appendLine("                ) { if (isRoot) root(entry, router) else destination(entry, router) }")
        appendLine("            }")
        appendLine("        }")
        appendLine("    }")
        appendLine("    router.sheet?.let { entry ->")
        appendLine("        key(entry.id) {")
        appendLine("            val host = remember { router.host(entry) }")
        appendLine("            sheet(entry, { router.updateSheet(null) }) {")
        appendLine("                BasekitStack(host, entry, Modifier, fillRoot = false, transition, destination, destination, sheet, fullScreenCover)")
        appendLine("            }")
        appendLine("        }")
        appendLine("    }")
        appendLine("    router.fullScreenCover?.let { entry ->")
        appendLine("        key(entry.id) {")
        appendLine("            val host = remember { router.host(entry) }")
        appendLine("            fullScreenCover(entry, { router.updateFullScreenCover(null) }) {")
        appendLine("                BasekitStack(host, entry, Modifier.fillMaxSize(), fillRoot = true, transition, destination, destination, sheet, fullScreenCover)")
        appendLine("            }")
        appendLine("        }")
        appendLine("    }")
        appendLine("}")
        appendLine()
        appendLine("/** How [BasekitNavigationStackHost] moves an entry: its offset as a share of the width and its opacity, at")
        appendLine(" * a progress from 0, shown, to 1, off screen, and how that progress runs, which is how long a popped")
        appendLine(" * entry stays on screen. */")
        appendLine("public class BasekitStackTransition(")
        appendLine("    public val offset: (Float) -> Float,")
        appendLine("    public val alpha: (Float) -> Float,")
        appendLine("    public val animationSpec: AnimationSpec<Float> = spring(dampingRatio = Spring.DampingRatioNoBouncy, stiffness = Spring.StiffnessMediumLow),")
        appendLine(") {")
        appendLine("    public companion object {")
        appendLine("        /** Slides in from the end, and back out to it. */")
        appendLine("        public val Slide: BasekitStackTransition = BasekitStackTransition(offset = { it }, alpha = { 1f })")
        appendLine("        /** Stays in place: for a host that moves the entry's contents itself. */")
        appendLine("        public val None: BasekitStackTransition = BasekitStackTransition(offset = { 0f }, alpha = { 1f })")
        appendLine("    }")
        appendLine("}")
    }

    private val DestinationInfo.routeClass: String get() = navName.toUpperCamelCase()
