package com.latenighthack.basekit.catalog.codegen

/**
 * Renders a [Catalog] as `catalog/v1` YAML. The output must parse with YAML 1.1 parsers such as
 * SnakeYAML, so:
 *
 *  - a map or list is written inline (`{ a: B }`) only when every entry is a bare identifier-like
 *    scalar; anything else, notably a nullable type such as `String?`, goes in block style;
 *  - scalars YAML 1.1 reads as booleans, nulls or numbers (`on`, `NO`, `null`, `1`) are quoted.
 *
 * Entries keep the order of the [Catalog]; the extractor makes that order stable.
 */
object CatalogYamlWriter {

    const val SCHEMA = "catalog/v1"

    private const val RULE = "─────────────────────────────────────────────"

    fun render(catalog: Catalog): String = buildString {
        appendLine("# Generated by basekit-catalog-ksp from @ViewModelSpec and @Destination declarations.")
        appendLine("# Do not edit: change the Kotlin declarations instead.")
        appendLine()
        appendLine("schema: $SCHEMA")
        appendLine()

        if (catalog.screens.isEmpty()) {
            appendLine("screens: {}")
        } else {
            appendLine("screens:")
            catalog.screens.forEachIndexed { index, screen ->
                if (index > 0) appendLine()
                header(screen.name)
                viewModel(screen, spaced = true)
            }
        }

        val groups = catalog.componentGroups.filter { it.components.isNotEmpty() }
        if (groups.isNotEmpty()) {
            appendLine()
            appendLine("components:")
            groups.forEachIndexed { index, group ->
                if (index > 0) appendLine()
                header(group.header)
                group.components.forEachIndexed { componentIndex, component ->
                    if (componentIndex > 0) appendLine()
                    viewModel(component, spaced = false)
                }
            }
        }

        if (catalog.types.isNotEmpty()) {
            appendLine()
            appendLine("types:")
            catalog.types.forEach { type(it) }
        }
    }

    private fun StringBuilder.header(title: String) {
        appendLine("  # $RULE")
        appendLine("  # $title")
        appendLine("  # $RULE")
        appendLine()
    }

    /** [spaced] separates the sections with blank lines, as screens are written in catalog/v1. */
    private fun StringBuilder.viewModel(vm: CatalogViewModel, spaced: Boolean) {
        appendLine("  ${scalar(vm.name)}:")
        appendLine("    spec: ${scalar(vm.spec)}")
        vm.navigation?.let { navigation ->
            appendLine("    navigation:")
            map("args", navigation.args, indent = 6, inlineLimit = 1)
            appendLine("      route: ${navigation.route?.let(::quoted) ?: "null"}")
            appendLine("      route_args: ${inlineList(navigation.routeArgs)}")
            appendLine("      response: ${navigation.response?.let(::scalar) ?: "null"}")
        }
        vm.identity?.let { appendLine("    identity: ${scalar(it)}") }

        fun section(present: Boolean, body: StringBuilder.() -> Unit) {
            if (!present) return
            if (spaced) appendLine()
            body()
        }

        section(vm.state.isNotEmpty()) { map("state", vm.state, indent = 4, inlineLimit = 0) }
        section(vm.actions.isNotEmpty()) {
            appendLine("    actions:")
            vm.actions.forEach { action ->
                val body = action.navigatesTo.takeIf { it.isNotEmpty() }
                    ?.let { "{ navigates_to: ${targets(it)} }" } ?: "{}"
                appendLine("      ${scalar(action.name)}: $body")
            }
        }
        section(vm.mutations.isNotEmpty()) {
            appendLine("    mutations:")
            vm.mutations.forEach { mutation(it) }
        }
        section(vm.lists.isNotEmpty()) {
            appendLine("    lists:")
            vm.lists.forEach { list ->
                appendLine("      ${scalar(list.name)}:")
                appendLine("        kind: ${list.kind.yamlName}")
                if (list.kind == CatalogListKind.SECTIONED && list.sections.isNotEmpty()) {
                    appendLine("        sections: ${inlineList(list.sections)}")
                }
                appendLine("        element: ${scalar(list.element)}")
                appendLine("        rows: ${inlineList(list.rows)}")
            }
        }
        section(vm.children.isNotEmpty()) { map("children", vm.children, indent = 4, inlineLimit = 0) }
    }

    private fun StringBuilder.mutation(mutation: CatalogMutation) {
        val name = scalar(mutation.name)
        val param = mutation.param
        val parts = buildList {
            add("param: { ${scalar(param.name)}: ${param.type} }")
            mutation.binds?.let { add("binds: ${scalar(it)}") }
            if (mutation.navigatesTo.isNotEmpty()) add("navigates_to: ${targets(mutation.navigatesTo)}")
        }
        if (flowSafe(param.name) && flowSafe(param.type)) {
            appendLine("      $name: { ${parts.joinToString(", ")} }")
            return
        }
        appendLine("      $name:")
        appendLine("        param:")
        appendLine("          ${scalar(param.name)}: ${scalar(param.type)}")
        mutation.binds?.let { appendLine("        binds: ${scalar(it)}") }
        if (mutation.navigatesTo.isNotEmpty()) appendLine("        navigates_to: ${targets(mutation.navigatesTo)}")
    }

    private fun StringBuilder.type(type: CatalogType) {
        val name = scalar(type.name)
        val entries = buildList {
            type.enumCases?.let { add("enum" to inlineList(it)) }
            type.subtypes?.let { add("subtypes" to inlineList(it)) }
            type.external?.let { add("external" to scalar(it)) }
        }
        val fields = type.fields
        val fieldsInline = fields != null && fields.all { flowSafe(it.name) && flowSafe(it.type) }
        if (fields == null || fieldsInline) {
            val all = entries + listOfNotNull(fields?.let { "fields" to inlineMap(it) })
            if (all.isEmpty()) {
                appendLine("  $name: {}")
            } else {
                appendLine("  $name: { ${all.joinToString(", ") { (key, value) -> "$key: $value" }} }")
            }
            return
        }
        appendLine("  $name:")
        entries.forEach { (key, value) -> appendLine("    $key: $value") }
        map("fields", fields, indent = 4, inlineLimit = 0)
    }

    /**
     * Writes `key:` and its entries. Up to [inlineLimit] flow-safe entries go on one line; an empty
     * map is always `{}`.
     */
    private fun StringBuilder.map(key: String, fields: List<CatalogField>, indent: Int, inlineLimit: Int) {
        val pad = " ".repeat(indent)
        val inline = fields.isEmpty() ||
            (fields.size <= inlineLimit && fields.all { flowSafe(it.name) && flowSafe(it.type) })
        if (inline) {
            appendLine("$pad$key: ${inlineMap(fields)}")
            return
        }
        appendLine("$pad$key:")
        fields.forEach { appendLine("$pad  ${scalar(it.name)}: ${scalar(it.type)}") }
    }

    private fun inlineMap(fields: List<CatalogField>): String =
        if (fields.isEmpty()) "{}" else fields.joinToString(", ", "{ ", " }") { "${it.name}: ${it.type}" }

    private fun inlineList(values: List<String>): String = values.joinToString(", ", "[", "]") { scalar(it) }

    private fun targets(names: List<String>): String = names.singleOrNull()?.let(::scalar) ?: inlineList(names)

    private val FLOW_SAFE = Regex("[A-Za-z_][A-Za-z0-9_.<>]*")
    private val BLOCK_SAFE = Regex("[A-Za-z_][A-Za-z0-9_.<>?, ]*")

    /** YAML 1.1 reads these plain scalars as booleans or null. */
    private val YAML11_RESERVED = setOf(
        "y", "yes", "n", "no", "true", "false", "on", "off", "null",
    )

    /** Whether [value] can appear unquoted inside `{ }` or `[ ]`. */
    internal fun flowSafe(value: String): Boolean =
        FLOW_SAFE.matches(value) && value.lowercase() !in YAML11_RESERVED

    /** [value] as a plain scalar when YAML 1.1 reads it back as the same string, else quoted. */
    internal fun scalar(value: String): String =
        if (BLOCK_SAFE.matches(value) && !value.endsWith(" ") && value.lowercase() !in YAML11_RESERVED) value
        else quoted(value)

    private fun quoted(value: String): String =
        value.replace("\\", "\\\\").replace("\"", "\\\"").let { "\"$it\"" }
}
