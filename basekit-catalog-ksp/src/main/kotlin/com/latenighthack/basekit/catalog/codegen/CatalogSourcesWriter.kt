package com.latenighthack.basekit.catalog.codegen

/**
 * Renders `catalog.sources.yaml`, written next to `catalog.yaml`: where each catalog entry is declared.
 *
 * ```yaml
 * root: /path/to/root/project
 * sources:
 *   Home: demo-core/src/commonMain/kotlin/com/example/HomeViewModel.kt:27
 *   Home.actions.onRefresh: demo-core/src/commonMain/kotlin/com/example/HomeViewModel.kt:45
 * ```
 *
 * Paths are relative to `root` when it is present. The catalog graph page reads this file to link each
 * entry to its source.
 */
object CatalogSourcesWriter {

    fun render(locations: CatalogLocations): String = buildString {
        appendLine("# Generated by basekit-catalog-ksp: where each catalog.yaml entry is declared.")
        appendLine()
        locations.root?.let { appendLine("root: ${quoted(it)}") }
        if (locations.entries.isEmpty()) {
            appendLine("sources: {}")
            return@buildString
        }
        appendLine("sources:")
        locations.entries.forEach { (key, value) -> appendLine("  ${quoted(key)}: ${quoted(value)}") }
    }

    private fun quoted(value: String): String =
        "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
}
