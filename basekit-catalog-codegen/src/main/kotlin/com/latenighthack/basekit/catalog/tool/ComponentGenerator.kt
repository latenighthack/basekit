package com.latenighthack.basekit.catalog.tool

/**
 * Writes the kotlin-inject component. Its factories (`homeFactory`, …) come from
 * `GeneratedViewModelFactories`, which basekit-viewmodel-ksp generates from the `@ViewModelInject`
 * implementations in the package they share; this adds a `create<Name>ViewModel` function per root
 * and the `@KmpComponentCreate` entry point. An app that needs a parent component writes its own
 * `@Component abstract class … (@Component val core: Core) : GeneratedViewModelFactories` instead.
 */
class ComponentGenerator(
    private val analysis: CatalogAnalysis,
    private val impls: ImplGenerator,
    private val packageName: String,
) {

    fun file(): GeneratedFile {
        val factoriesPackage = commonPackage(analysis.roots.map { it.packageName })
        val imports = mutableSetOf(
            Symbols.COMPONENT,
            Symbols.KMP_COMPONENT_CREATE,
            listOf(factoriesPackage, FACTORIES).filter { it.isNotEmpty() }.joinToString("."),
        )
        val entries = analysis.screens.map { it to impls.assistedParams(it) } +
            analysis.rootComponents.map { it to emptyList() }
        val members = entries.map { (vm, params) ->
            imports += vm.spec
            params.forEach { imports += it.imports }
            val signature = params.joinToString(", ") { "${it.name}: ${it.type}" }
            val call = params.joinToString(", ") { it.name }
            "fun create${vm.name}ViewModel($signature): ${vm.specName} = ${vm.name.decapitalized()}Factory($call)"
        }
        val body = buildString {
            appendLine("@Component")
            appendLine("abstract class ViewModelComponent : $FACTORIES {")
            appendLine(members.joinToString("\n\n").indent(4))
            appendLine("}")
            appendLine()
            appendLine("@KmpComponentCreate")
            append("expect fun createViewModelComponent(): ViewModelComponent")
        }
        return GeneratedFile(
            sourcePath(packageName, "ViewModelComponent"),
            kotlinFile(packageName, SpecGenerator.HEADER, imports, body),
            overwrite = true,
        )
    }

    companion object {
        /** Generated by basekit-viewmodel-ksp (ViewModelFactoriesGenerator). */
        const val FACTORIES = "GeneratedViewModelFactories"
    }
}
